 assert.equal(await page.getByRole('switch',{name:'自动刷新',exact:true}).getAttribute('aria-checked'),'false')
 await page.getByRole('button',{name:'编辑',exact:true}).click()
 await page.getByRole('button',{name:'进入编辑模式',exact:true}).click()
 await page.locator('.cm-content').waitFor()
 assert.ok((await page.locator('.cm-content').innerText()).includes('用户补充说明'))
 assert.equal(await page.evaluate(()=>window.logAudit.calls.filter(c=>c.command.startsWith('write_')).length),0)
 assert.deepEqual(errors,[])
 await fs.writeFile(output+'/results.json',JSON.stringify({checks:['Level and text filtering','Named refresh and tail switches','Narrow container labels','Editing notice preserved','Undo/redo and viewer/editor draft restoration'],errors,scope:'Actual LogViewerView and CodeMirror; native read/range mocked; no native writes, growing-file or large-file acceptance',releaseCandidate:false},null,2)+'\n')
 console.log('Log page checks passed')
