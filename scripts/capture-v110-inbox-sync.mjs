import fs from 'node:fs/promises'
const original=await fs.readFile(new URL('./capture-v110-quick-note-windows.mjs',import.meta.url),'utf8')
const prefix=original.slice(0,original.indexOf('try{\n  let mainTarget'))
if(!prefix || prefix===original)throw Error('Native connection helper changed')
const scenario=String.raw`
try {
  let mainTarget
  await wait(async()=>{try{mainTarget=(await targets()).find(t=>t.type==='page');return !!mainTarget}catch{return false}},'main')
  const main=await connect(mainTarget)
  await wait(()=>main.evaluate("document.body.innerText.includes('Note.md')"),'main ready')
  await main.evaluate("window.__TAURI_INTERNALS__.invoke('open_quick_note')")
  let qt
  await wait(async()=>{qt=(await targets()).find(t=>t.url.includes('quick-note'));return !!qt},'quick window')
  const quick=await connect(qt),lib=process.env.LONGEDIT_E2E_LIBRARY
  await wait(()=>quick.evaluate("!!document.querySelector('textarea') && !document.querySelector('[aria-label=资料库]').disabled"),'quick ready')
  await fs.mkdir(output,{recursive:true})
  await fs.writeFile(path.join(output,'initial-quick.png'),Buffer.from((await quick.send('Page.captureScreenshot',{format:'png'})).data,'base64'))
  for(const name of ['收集A','收集B'])await fs.mkdir(path.join(lib,name))
  const broadcast=(connection,relative)=>connection.evaluate("import('/node_modules/@tauri-apps/api/event.js').then(m=>m.emit('inbox-directory-changed',"+JSON.stringify({root:lib,relative})+"))")
  await main.evaluate("import('/src/store/app.ts').then(m=>m.useAppStore().setInboxDirectory("+JSON.stringify(lib)+","+JSON.stringify(path.join(lib,'收集A'))+"))")
  await broadcast(main,'收集A')
  await wait(()=>quick.evaluate("document.querySelector('[aria-label=保存到]').value.endsWith('/收集A')"),'idle window follows main setting')
  checks.push('native quick window follows main library configuration event')
  await quick.evaluate("document.querySelector('textarea').focus()")
  await quick.send('Input.insertText',{text:'整理会议：不要改变正在保存的目录'})
  await quick.evaluate("(()=>{const e=document.querySelector('[aria-label=保存后操作]');e.value='open';e.dispatchEvent(new Event('change',{bubbles:true}))})()")
  await main.send('Debugger.enable');await main.send('Debugger.pause')
  try {
    await click(quick,"[...document.querySelectorAll('button')].find(e=>e.textContent==='保存笔记')")
    await wait(()=>quick.evaluate("document.querySelector('header').textContent.includes('正在保存')"),'handoff pending')
    await broadcast(quick,'收集B')
    check('busy operation retains original destination',await quick.evaluate("document.querySelector('[aria-label=保存到]').value.endsWith('/收集A')"))
    await wait(()=>quick.evaluate("document.querySelector('[role=status]').textContent.includes('主窗口未响应')"),'timeout leaves saved receipt')
  } finally { await main.send('Debugger.resume');await main.send('Debugger.disable') }
  await wait(()=>quick.evaluate("!document.querySelector('[aria-label=资料库]').disabled"),'quick operation settled')
  const follows=await quick.evaluate("document.querySelector('[aria-label=保存到]').value.endsWith('/收集B')")
  await fs.writeFile(path.join(output,'after-handoff.png'),Buffer.from((await quick.send('Page.captureScreenshot',{format:'png'})).data,'base64'))
  await fs.writeFile(path.join(output,'observations.json'),JSON.stringify({checks,followsLatestInboxAfterBusy:follows,scope:'Native windows; setting event during paused-main handoff; not slow-disk simulation'},null,2))
  check('after completed save, next capture follows newest inbox',follows)
  const files=await fs.readdir(path.join(lib,'收集A'))
  check('first note remains in original destination',files.length===1 && (await fs.readFile(path.join(lib,'收集A',files[0]),'utf8')).includes('整理会议'))
  check('inbox preference retains semantic selection',await quick.evaluate('localStorage.getItem('+JSON.stringify('longedit.quick-note.target:'+lib)+')')==='__inbox')
  await quick.evaluate("(()=>{const e=document.querySelector('[aria-label=保存后操作]');e.value='continue';e.dispatchEvent(new Event('change',{bubbles:true}));document.querySelector('textarea').focus()})()")
  await quick.send('Input.insertText',{text:'下一条记录应进入新的收集目录'})
  await click(quick,"[...document.querySelectorAll('button')].find(e=>e.textContent==='保存笔记')")
  await wait(()=>quick.evaluate("document.querySelector('[role=status]').textContent.includes('已保存：')"),'second save')
  const second=await fs.readdir(path.join(lib,'收集B'))
  check('next real note is written into latest inbox',second.length===1 && (await fs.readFile(path.join(lib,'收集B',second[0]),'utf8')).includes('下一条记录'))
  await wait(()=>quick.evaluate("!document.querySelector('[aria-label=资料库]').disabled"),'second save settled')
  await quick.evaluate("(()=>{const e=document.querySelector('[aria-label=保存到]');e.value="+JSON.stringify(lib)+";e.dispatchEvent(new Event('change',{bubbles:true}));document.querySelector('textarea').focus()})()")
  await quick.send('Input.insertText',{text:'草稿仍在，不要代替我保存'})
  await broadcast(main,'收集A')
  check('explicit custom target is not redirected',await quick.evaluate("document.querySelector('[aria-label=保存到]').value")===lib)
  check('configuration event preserves unsaved draft',await quick.evaluate("document.querySelector('textarea').value==='草稿仍在，不要代替我保存'"))
  // Select the inbox deliberately, then force a real filesystem save failure in this fixture.
  await quick.evaluate("(()=>{const e=document.querySelector('[aria-label=保存到]');e.value="+JSON.stringify(lib.replaceAll('\\','/')+'/收集A')+";if(e.selectedIndex<0)e.selectedIndex=0;e.dispatchEvent(new Event('change',{bubbles:true}))})()")
  await fs.writeFile(path.join(lib,'收集C'),'occupied fixture path')
  await broadcast(main,'收集C')
  await wait(()=>quick.evaluate("document.querySelector('[aria-label=保存到]').value.endsWith('/收集C')"),'new inbox selected')
  await click(quick,"[...document.querySelectorAll('button')].find(e=>e.textContent==='保存笔记')")
  await wait(()=>quick.evaluate("document.querySelector('[role=status]').textContent.includes('保存失败')"),'real write failure')
  await broadcast(main,'收集A')
  check('failed operation keeps retry destination and draft',await quick.evaluate("document.querySelector('[aria-label=保存到]').value.endsWith('/收集C') && document.querySelector('textarea').value==='草稿仍在，不要代替我保存'"))
  await fs.unlink(path.join(lib,'收集C'))
  await fs.mkdir(path.join(lib,'收集C'))
  await click(quick,"[...document.querySelectorAll('button')].find(e=>e.textContent==='保存笔记')")
  await wait(()=>quick.evaluate("document.querySelector('[role=status]').textContent.includes('已保存：') && !document.querySelector('[aria-label=资料库]').disabled"),'retry succeeds')
  await wait(()=>quick.evaluate("document.querySelector('[aria-label=保存到]').value.endsWith('/收集A')"),'retry unlocks latest inbox')
  check('successful retry saves once before following latest inbox',(await fs.readdir(path.join(lib,'收集C'))).length===1)
  await fs.writeFile(path.join(output,'checks.json'),JSON.stringify({checks},null,2))
  console.log(JSON.stringify(checks))
} finally { for(const c of connections)c.socket.close() }
`
try { await import('data:text/javascript;base64,'+Buffer.from(prefix+scenario).toString('base64')) }
catch(error){console.error(error.message);process.exitCode=1}
