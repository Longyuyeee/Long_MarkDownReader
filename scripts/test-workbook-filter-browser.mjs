import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve('docs/evidence/v110-workbook-filter-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workbook-save-browser.html?filter=1')
  await page.locator('.workbook-cell').first().click()
  await page.locator('.tool-panel-trigger').click()
  await page.getByText('数据、Table 与规则', { exact: true }).click()
  await page.getByTitle('筛选字段', { exact: true }).selectOption('0')
  const query = page.getByPlaceholder('包含筛选', { exact: true })
  await query.fill('客户')
  await page.getByRole('button', { name: '应用到文件', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingFilter)
  assert.equal(await query.isDisabled(), true)
  await page.evaluate(() => window.workbookAudit.pendingFilter(true))
  await page.getByText('tasks.xlsx 筛选条件保存失败：模拟筛选写入失败', { exact: true }).waitFor()
  assert.equal(await query.inputValue(), '客户')
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '01-filter-failure.png') })
  await page.getByRole('button', { name: '应用到文件', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingFilter)
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet2' }).click()
  await page.getByText('第二张表的客户清单', { exact: true }).waitFor()
  await page.evaluate(() => window.workbookAudit.pendingFilter(false))
  await page.getByText('筛选与排序条件已写入 XLSX', { exact: true }).waitFor()
  assert.equal((await page.locator('.sheet-tabs button.active').innerText()).trim(), 'Sheet2')
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet1' }).click()
  await query.waitFor(); assert.equal(await query.inputValue(), '客户')
  await page.getByRole('button', { name: '清除条件', exact: true }).click()
  const dialog = page.getByRole('dialog').filter({ hasText: '清除筛选与排序条件？' })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' }); assert.equal(await query.inputValue(), '客户')
  await page.getByRole('button', { name: '清除条件', exact: true }).click()
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '02-clear-confirmation.png') })
  await dialog.getByRole('button', { name: '清除条件', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingFilter)
  await page.evaluate(() => window.workbookAudit.pendingFilter(false))
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await query.inputValue(), '')
  await page.getByText('客户交付', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: filter failure/retry/sheet switch/clear cancellation and confirmation; simulated IPC only')
} finally { await browser.close() }
