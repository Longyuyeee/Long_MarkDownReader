 await modal.getByRole('button',{name:'保存样式',exact:true}).click()
 await modal.waitFor({state:'hidden'})
 assert.ok(await page.evaluate(()=>window.shellAudit.store.fileDisplayStyleForPath('C:/shell-fixture/项目方案.md')))
 assert.equal(await page.evaluate(()=>window.shellAudit.store.fileDisplayStyleForPath('\\\\?\\c:\\SHELL-fixture\\项目方案.md').selectedBackgroundColor),'#243e59')
 await open()
 assert.equal(await modal.getByRole('button',{name:'项目',exact:true}).getAttribute('aria-pressed'),'true')
 await modal.locator('.file-style-editor').evaluate(element=>element.scrollTop=0)
 await page.screenshot({path:output+'/03-selected-colors.png',animations:'disabled'})
