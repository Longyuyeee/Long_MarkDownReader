 assert.equal(await page.evaluate(()=>Object.keys(window.shellAudit.store.fileDisplayStyles).length),0)
 assert.deepEqual(errors,[])
 await fs.writeFile(output+'/results.json',JSON.stringify({checks:['520px cap on 1600px window','30 labelled icon choices','Normal/selected previews with exact custom colors','Cancel without persistence','Save, canonical-path lookup, reopen and reset','Fill, outline and side-marker modes preserve their independent choices','360x520 scrollable content and reachable footer'],errors,scope:'Actual Vue components, mocked config IPC'},null,2)+'\n')
 console.log('File style modal checks passed')
