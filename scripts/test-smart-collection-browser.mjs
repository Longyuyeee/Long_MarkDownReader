import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const out = path.resolve(process.env.LONGEDIT_COLLECTION_AUDIT_OUTPUT || 'docs/evidence/v110-smart-collection')
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/history-browser.html')
  await page.locator('#tab-collections').click()
  const panel = page.getByRole('region', { name: '智能集合条件' })
  await panel.getByRole('button', { name: '新建集合', exact: true }).click()
  await panel.getByLabel('集合名称', { exact: true }).fill('本周项目笔记')
  await panel.locator('.collection-range > summary').click()
  await panel.getByLabel('文件夹', { exact: true }).fill('项目')
  await panel.getByLabel('笔记标签', { exact: true }).fill('项目')
  await panel.getByLabel('修改时间').selectOption('7')
  await panel.getByRole('button', { name: '查看资料' }).click()
  await panel.getByText('1 项', { exact: true }).waitFor()
  const request = await page.evaluate(() => window.historyAudit.calls.find(c => c.command === 'search_smart_collection').args)
  assert.equal(request.query, '')
  assert.deepEqual(request.filters, { directory: '项目', tag: '项目', modifiedWithinDays: 7 })
  await panel.getByRole('button', { name: /B.md/ }).click()
  await page.waitForFunction(() => window.historyAudit.store.activeTabId === 'C:/audit/B.md')
  await panel.getByRole('button', { name: '调整条件', exact: true }).click()
  await page.evaluate(() => { window.historyAudit.failSave = true })
  await panel.getByRole('button', { name: '保存集合' }).click()
  await panel.getByRole('alert').waitFor()
  assert.equal(await page.evaluate(() => window.historyAudit.store.savedSearches.length), 0)
  assert.equal(await panel.getByLabel('集合名称', { exact: true }).inputValue(), '本周项目笔记')
  await page.evaluate(() => { window.historyAudit.failSave = false })
  await panel.getByRole('button', { name: '保存集合' }).click()
  await panel.getByText(/集合已保存/).waitFor()
  await panel.getByRole('button', { name: '我的集合', exact: true }).click()
  await page.locator('.collection-open').filter({ hasText: '本周项目笔记' }).click()
  await panel.getByText('1 项', { exact: true }).waitFor()
  await panel.getByRole('button', { name: '调整条件', exact: true }).click()
  await panel.getByLabel('文件夹', { exact: true }).fill('项目/设计')
  assert.equal(await panel.getByRole('button', { name: /B.md/ }).count(), 0)
  await panel.getByRole('button', { name: '保存修改' }).click()
  await page.waitForFunction(() => window.historyAudit.store.savedSearches[0]?.filters.directory === '项目/设计')
  assert.equal(await page.evaluate(() => window.historyAudit.store.savedSearches.length), 1)
  await panel.getByRole('button', { name: '刷新', exact: true }).click()
  await panel.getByText('1 项', { exact: true }).waitFor()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(out, '01-actual-collections.png') })
  await page.setViewportSize({ width: 640, height: 800 })
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  if (await page.getByRole('button', { name: '导航', exact: true }).getAttribute('aria-expanded') === 'false') await page.getByRole('button', { name: '导航', exact: true }).click()
  await page.screenshot({ path: path.join(out, '02-narrow.png') })
  assert.equal(await panel.evaluate(el => el.scrollWidth > el.clientWidth), false)
  await page.evaluate(() => { window.historyAudit.deferCollection = true })
  await panel.getByRole('button', { name: '刷新', exact: true }).click()
  await page.waitForFunction(() => !!window.historyAudit.resolveCollection)
  await panel.getByRole('button', { name: '调整条件', exact: true }).click()
  await panel.getByLabel('文件夹', { exact: true }).fill('其他')
  await page.evaluate(() => window.historyAudit.resolveCollection({ results: [{ title: '迟到结果', path: 'C:/audit/late.md' }], truncated: false }))
  assert.equal(await panel.getByText('迟到结果').count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: actual LibraryMode collection filters, main-editor opening, failed-save retention, edit and stale-result isolation; mocked IPC')
} finally { await browser.close() }
