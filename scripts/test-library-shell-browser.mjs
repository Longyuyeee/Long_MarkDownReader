import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = 'docs/evidence/v110-shell-implementation'
await fs.mkdir(output, {recursive:true})
const browser = await chromium.launch({channel:'msedge',headless:true})
const checks = [], errors = []
try {
  const page = await browser.newPage({viewport:{width:1280,height:820}})
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/library-shell-browser.html')
  await page.locator('.vditor-wysiwyg').getByText('让记录更顺手',{exact:true}).waitFor()
  await page.screenshot({path:output+'/01-main.png'})
  for (const key of ['files','outline','quick','collections','tags','links','history']) {
    assert.equal(await page.locator(`#tab-${key} .icon-tab-text`).isVisible(),true)
    await page.locator(`#tab-${key}`).click()
    await page.locator(`#panel-${key}`).waitFor()
  }
  await page.locator('#tab-files').click()
  checks.push('seven labeled navigation panels reachable')
  await page.getByRole('button',{name:'导航',exact:true}).click()
  assert.equal(await page.locator('#library-navigation').getAttribute('aria-hidden'),'true')
  await page.getByRole('button',{name:'导航',exact:true}).click()
  assert.equal(await page.locator('#library-navigation').getAttribute('aria-hidden'),'false')
  checks.push('navigation toggle updates visibility and keyboard access')
  await page.locator('[data-testid="library-document-menu"]').click()
  const menu = page.getByLabel('文档操作菜单')
  await menu.waitFor()
  await page.waitForTimeout(200)
  for (const label of ['重新读取文件','编码与换行','导出','转脑图','历史与差异','专注写作']) assert.match(await menu.innerText(),new RegExp(label))
  await menu.getByRole('button',{name:'源码',exact:true}).click()
  await page.waitForFunction(() => window.shellAudit.store.editorMode === 'sv')
  await menu.getByRole('button',{name:'所见',exact:true}).click()
  await page.waitForFunction(() => window.shellAudit.store.editorMode === 'wysiwyg')
  await page.locator('.vditor-wysiwyg [contenteditable="true"]').first().waitFor({state:'visible'})
  await menu.getByRole('button',{name:'窄',exact:true}).click()
  assert.equal(await page.locator('.editor-width-narrow').count(),1)
  await menu.getByRole('button',{name:'中',exact:true}).click()
  await menu.getByRole('button',{name:'导出',exact:true}).click()
  await page.getByText('导出 HTML',{exact:true}).waitFor()
  await page.waitForTimeout(200)
  await page.screenshot({path:output+'/02-document-menu.png'})
  await page.locator('[data-testid="library-document-menu"]').click()
  await menu.waitFor({state:'hidden'})
  checks.push('document menu keeps modes, widths and export submenu')
  await page.locator('#vditor-lib [data-type="more"]').first().click()
  for (const name of ['table','code','editor-bg','ai-assist','preview','edit-mode']) assert.equal(await page.locator(`#vditor-lib [data-type="${name}"]`).count() > 0,true)
  await page.screenshot({path:output+'/03-more-format.png'})
  await page.mouse.click(800,200)
  checks.push('all secondary Vditor tools remain in native more menu')
  const input = page.locator('.vditor-wysiwyg [contenteditable="true"]').first()
  await input.click(); await page.keyboard.press('Control+End'); await page.keyboard.type(' appended draft')
  await page.waitForFunction(() => window.shellAudit.store.tabs.find(t => t.id === window.shellAudit.store.activeTabId).isDirty)
  await page.evaluate(() => {window.shellAudit.failSave = true})
  await page.locator('[data-testid="library-explicit-save"]').click()
  await page.getByText(/保存失败/).first().waitFor()
  assert.match(await input.innerText(),/appended draft/)
  await page.evaluate(() => {window.shellAudit.failSave = false})
  await page.locator('[data-testid="library-explicit-save"]').click()
  await page.waitForFunction(() => !window.shellAudit.store.tabs.find(t => t.id === window.shellAudit.store.activeTabId).isDirty)
  assert.match(await page.evaluate(() => window.shellAudit.disk.get(window.shellAudit.store.activeTabId)),/appended draft/)
  checks.push('visible explicit save retains failed draft and retries through production handler')
  await page.locator('[data-testid="library-reference-toggle"]').click()
  await page.getByRole('button',{name:'查找资料',exact:true}).click()
  const search = page.getByRole('textbox',{name:'搜索文件与正文'})
  await search.fill('保存的位置')
  await page.getByRole('button',{name:/在侧边参考 会议记录/}).click()
  await page.locator('.search-document-preview .preview-text').getByText(/保存的位置/).waitFor()
  await page.locator('[data-testid="library-reference-toggle"]').click()
  assert.equal(await page.locator('.search-document-preview').count(),0)
  await page.locator('[data-testid="library-reference-toggle"]').click()
  await page.locator('.search-document-preview').waitFor()
  await page.screenshot({path:output+'/04-reference.png'})
  checks.push('reference search, explicit dock and toggle retain source identity')
  await page.locator('[data-testid="library-focus-toggle"]').click()
  assert.equal(await page.locator('.library-shell-toolbar').count(),0)
  assert.equal(await page.locator('.search-document-preview').count(),0)
  await page.getByRole('button',{name:'退出专注',exact:true}).click()
  await page.locator('.library-shell-toolbar').waitFor()
  checks.push('focus mode exits visibly and reference returns')
  for (const width of [736,320]) {
    await page.setViewportSize({width,height:820})
    await page.waitForTimeout(250)
    assert.equal(await page.locator('#library-navigation').getAttribute('aria-hidden'),'true')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true)
    await page.screenshot({path:output+`/05-reference-${width}.png`})
    await page.locator('[data-testid="library-reference-toggle"]').click()
    await page.getByRole('button',{name:'导航',exact:true}).click()
    await page.locator('#tab-outline').click()
    await page.locator('#panel-outline').waitFor({state:'visible'})
    assert.equal(await page.locator('#panel-outline').isVisible(),true)
    await page.getByRole('button',{name:'导航',exact:true}).click()
    await page.locator('[data-testid="library-document-menu"]').click()
    await page.getByLabel('文档操作菜单').waitFor()
    await page.waitForTimeout(200)
    const bounds = await page.getByLabel('文档操作菜单').boundingBox()
    await page.screenshot({path:output+`/06-menu-${width}.png`})
    assert.equal(bounds.x >= 0 && bounds.x + bounds.width <= width,true,JSON.stringify({width,bounds}))
    await page.locator('[data-testid="library-document-menu"]').click()
    await page.getByLabel('文档操作菜单').waitFor({state:'hidden'})
    await page.locator('[data-testid="library-reference-toggle"]').click()
  }
  checks.push('736 and 320 widths keep editor, navigation, reference and menu reachable')
  await page.getByRole('button',{name:'快速笔记',exact:true}).click()
  await page.waitForFunction(() => window.shellAudit.calls.some(c => c.command === 'open_quick_note'))
  await page.getByRole('button',{name:'命令',exact:true}).click()
  assert.equal(await page.evaluate(() => window.shellAudit.commands),1)
  checks.push('quick note and command entry trigger existing actions')
  assert.deepEqual(errors,[])
  await fs.writeFile(output+'/checks.json',JSON.stringify({scope:'actual Vue LibraryMode and Vditor, mocked Tauri IPC; no native disk/install evidence',checks,errors},null,2)+'\n')
  console.log(JSON.stringify({checks}))
} finally {await browser.close()}
