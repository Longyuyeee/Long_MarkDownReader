import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve('docs/evidence/v110-workbook-save-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  // Isolated clipboard simulator: never reads or writes the user's clipboard.
  await page.addInitScript(() => {
    const audit = window.clipboardAudit = { read: null, write: null, copied: '' }
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: {
      readText: () => new Promise(resolve => { audit.read = value => { audit.read = null; resolve(value) } }),
      writeText: text => new Promise(resolve => { audit.copied = text; audit.write = () => { audit.write = null; resolve() } }),
    } })
  })
  const errors = []; page.on('pageerror', error => { errors.push(error.message); console.error(error.message) })
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workbook-save-browser.html')
  const cell = page.locator('.workbook-cell').first()
  await cell.waitFor(); await cell.dblclick()
  const formula = page.locator('input[placeholder="当前单元格不可编辑"]')
  await formula.fill('先核对交付日期'); await formula.press('Enter')
  await page.screenshot({ path: path.join(output, '01-draft.png') })
  await page.getByRole('button', { name: '保存 (1)', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pending)
  assert.equal(await formula.isDisabled(), true)
  // The grid shortcut must respect the same save boundary as the disabled toolbar.
  await cell.click()
  await page.keyboard.press('Control+z')
  assert.equal(await formula.inputValue(), '先核对交付日期')
  assert.equal(await cell.locator('.cell-content').innerText(), '先核对交付日期')
  await page.keyboard.press('Delete')
  assert.equal(await formula.inputValue(), '先核对交付日期')
  await page.evaluate(() => { window.workbookAudit.failNext = true; window.workbookAudit.pending() })
  await page.getByText('tasks.xlsx 保存失败：模拟磁盘失败', { exact: true }).waitFor()
  await page.waitForTimeout(250) // Let the actual message enter animation finish for the screenshot.
  assert.equal(await formula.inputValue(), '先核对交付日期')
  await page.screenshot({ path: path.join(output, '02-failed.png') })
  await page.getByRole('button', { name: '保存 (1)', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pending)
  await page.evaluate(() => window.workbookAudit.pending())
  await page.getByRole('button', { name: '已保存', exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  await page.screenshot({ path: path.join(output, '03-saved.png') })
  await cell.dblclick()
  await formula.fill('保存后不要跳回原工作表'); await formula.press('Enter')
  await page.getByRole('button', { name: '保存 (1)', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pending)
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet2' }).click()
  await page.getByText('第二张表的客户清单', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(output, '04-sheet2-during-save.png') })
  await page.evaluate(() => window.workbookAudit.pending())
  await page.getByRole('button', { name: '已保存', exact: true }).waitFor()
  assert.equal((await page.locator('.sheet-tabs button.active').innerText()).trim(), 'Sheet2')
  await page.getByText('第二张表的客户清单', { exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  await page.screenshot({ path: path.join(output, '05-sheet2-after-save.png') })
  // Switch sheets while saving, but let that sheet read finish after the receipt.
  await cell.dblclick()
  await formula.fill('第二张表补充客户记录'); await formula.press('Enter')
  await page.getByRole('button', { name: '保存 (1)', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pending)
  await page.evaluate(() => { window.workbookAudit.holdReads = true })
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet1' }).click()
  await page.waitForFunction(() => window.workbookAudit.readQueue.length === 1)
  await page.evaluate(() => window.workbookAudit.pending())
  await page.waitForFunction(() => window.workbookAudit.readQueue.length === 2)
  await page.evaluate(() => window.workbookAudit.readQueue[1].resolve())
  await page.getByRole('button', { name: '已保存', exact: true }).waitFor()
  await page.getByText('保存后不要跳回原工作表', { exact: true }).waitFor()
  await page.evaluate(() => { window.workbookAudit.readQueue[0].reject(); window.workbookAudit.holdReads = false })
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  assert.equal((await page.locator('.sheet-tabs button.active').innerText()).trim(), 'Sheet1')
  assert.equal(await page.getByText('过期读取失败', { exact: false }).count(), 0)
  await page.screenshot({ path: path.join(output, '06-sheet1-after-pending-read.png') })
  await cell.click()
  await page.keyboard.press('Control+v')
  await page.waitForFunction(() => !!window.clipboardAudit.read)
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet2' }).click()
  await page.getByText('第二张表补充客户记录', { exact: true }).waitFor()
  await page.evaluate(() => window.clipboardAudit.read('不应该粘贴到新的工作表'))
  await page.getByText('编辑状态已变化，请在目标选区重新粘贴', { exact: true }).waitFor()
  assert.equal(await cell.locator('.cell-content').innerText(), '第二张表补充客户记录')
  await cell.click()
  await page.keyboard.press('Control+x')
  await page.waitForFunction(() => !!window.clipboardAudit.write)
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet1' }).click()
  await page.getByText('保存后不要跳回原工作表', { exact: true }).waitFor()
  await page.evaluate(() => window.clipboardAudit.write())
  await page.getByText('编辑状态已变化，已复制内容但未清除单元格', { exact: true }).waitFor()
  assert.equal(await cell.locator('.cell-content').innerText(), '保存后不要跳回原工作表')
  await page.waitForTimeout(250)
  await page.screenshot({ path: path.join(output, '07-stale-clipboard-blocked.png') })
  // Valid-context clipboard operations must still work.
  await cell.click(); await page.keyboard.press('Control+v')
  await page.waitForFunction(() => !!window.clipboardAudit.read)
  await page.evaluate(() => window.clipboardAudit.read('当前选区正常粘贴'))
  await page.getByText('当前选区正常粘贴', { exact: true }).waitFor()
  await page.locator('.tool-panel-trigger').click()
  await page.getByText('单元格格式', { exact: true }).click()
  await page.getByTitle('设置选中行的行高', { exact: true }).click()
  await page.locator('.app-prompt-content input').fill('30')
  await page.getByRole('button', { name: '应用行高', exact: true }).click()
  await page.getByRole('button', { name: '保存 (2)', exact: true }).waitFor()
  await page.getByTitle('设置选中列的列宽', { exact: true }).click()
  await page.locator('.app-prompt-content input').fill('25')
  await page.getByRole('button', { name: '应用列宽', exact: true }).click()
  await page.getByRole('button', { name: '保存 (3)', exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  await page.getByTitle('编辑自定义数字格式', { exact: true }).click()
  await page.locator('.app-prompt-content input').fill('0.000')
  await page.getByRole('button', { name: '应用格式', exact: true }).waitFor({ state: 'visible' })
  await page.waitForTimeout(300) // Let the dialog enter transition finish before visual evidence.
  await page.screenshot({ path: path.join(output, '08-custom-format-dialog.png') })
  await page.getByRole('button', { name: '应用格式', exact: true }).click()
  await page.getByRole('button', { name: '保存 (4)', exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  await page.screenshot({ path: path.join(output, '09-format-drafts.png') })
  assert.deepEqual(errors, [])
  console.log('PASS: WorkbookView save shortcuts, clipboard context, failure/retry, sheet switching and format dialogs; simulated IPC/clipboard only')
} finally { await browser.close() }
