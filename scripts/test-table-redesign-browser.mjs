import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import fs from 'node:fs/promises'
const {chromium}=createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE||'playwright')
const output='docs/evidence/v110-table-redesign'
await fs.mkdir(output,{recursive:true})
const browser=await chromium.launch(),errors=[]
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}})
 page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:9000/scripts/fixtures/table-redesign-browser.html')
 await page.locator('.table-row').first().waitFor()
 await page.getByPlaceholder('筛选所有字段').fill('交付')
 assert.equal(await page.locator('.table-row').count(),1)
 await page.getByRole('button',{name:'清除筛选',exact:true}).click()
 await page.getByRole('button',{name:'＋ 行',exact:true}).click()
 assert.equal(await page.locator('.table-row').count(),3)
 await page.getByTitle('撤销数据修改 (Ctrl+Z)').click()
 assert.equal(await page.locator('.table-row').count(),2)
 await page.screenshot({path:output+'/01-grid-wide.png',animations:'disabled'})
 await page.evaluate(()=>document.querySelector('#app').style.width='480px')
 const save=await page.locator('.save-button').boundingBox()
 assert.ok(save.x>=0 && save.x+save.width<=480)
 await page.screenshot({path:output+'/02-grid-container.png',animations:'disabled'})
 await page.getByRole('tab',{name:'看板',exact:true}).click()
 await page.locator('.board-card').first().waitFor()
 await page.locator('.board-field-picker summary').click()
 const menu=await page.locator('.board-field-menu').boundingBox()
 assert.ok(menu.x>=0 && menu.x+menu.width<=480)
 await page.locator('.board-field-menu button').filter({hasText:'金额'}).click()
 await page.locator('.board-field-picker summary').click()
 await page.screenshot({path:output+'/03-board-container.png',animations:'disabled'})
 await page.getByRole('tab',{name:'图表',exact:true}).click()
 await page.locator('.chart-preview svg').waitFor()
 const settings=await page.locator('.chart-settings').boundingBox(),preview=await page.locator('.chart-preview').boundingBox()
 assert.ok(preview.y>=settings.y+settings.height-1)
 const svg=await page.locator('.chart-preview svg').boundingBox()
 assert.ok(svg.x>=0 && svg.x+svg.width<=480)
 await page.locator('.chart-types button').filter({hasText:'折线'}).click()
 await page.screenshot({path:output+'/04-chart-container.png',animations:'disabled'})
 await page.getByRole('tab',{name:'仪表盘',exact:true}).click()
 await page.locator('.dashboard-card').waitFor()
 await page.getByTitle('调整卡片宽度').click()
 const card=await page.locator('.dashboard-card').boundingBox()
 assert.ok(card.width>400 && card.x+card.width<=480)
 await page.screenshot({path:output+'/05-dashboard-container.png',animations:'disabled'})
 await page.setViewportSize({width:480,height:900})
 await page.getByTitle('编辑源图表').click()
 await page.locator('.chart-settings').waitFor()
 await page.screenshot({path:output+'/06-chart-window.png',animations:'disabled'})
 assert.equal(await page.evaluate(()=>window.tableUiAudit.calls.filter(c=>c.command.startsWith('write_')).length),0)
 assert.deepEqual(errors,[])
 await fs.writeFile(output+'/results.json',JSON.stringify({checks:['Grid filter/add/undo','Visible save at 480px','Board field menu click','Chart type switch and stacked preview','Dashboard card width and edit-source navigation'],errors,scope:'Actual TableView/ChartEditor/Dashboard, native read mocked; no write/export or drag-drop acceptance',releaseCandidate:false},null,2)+'\n')
 console.log('Table four-view layout and interaction checks passed')
} finally {await browser.close()}
