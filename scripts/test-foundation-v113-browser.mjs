  assert.equal(saved.tabs[0].pinned, true)
  checks.push('Tab context menu pins, bulk close preserves pinned tabs, Ctrl+Shift+T reopens and drag order/pins persist')
  await page.locator('#tab-tags').click()
  const projectTag = page.locator('#panel-tags .tag-item').filter({ hasText: '项目' })
