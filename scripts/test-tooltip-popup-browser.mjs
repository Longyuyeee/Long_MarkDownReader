import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'

const { chromium } = createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = 'docs/evidence/v110-tooltip-popup'
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.LONGEDIT_BROWSER_CHANNEL || undefined, headless: true })
const errors = [], checks = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 820 } })
  page.setDefaultTimeout(10000)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workflow-redesign-browser.html')
  await page.getByRole('link', { name: '资料库', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('[data-testid="library-document-preview"]').disabled)
  await page.evaluate(async () => {
    const { installAppTooltipPolicy } = await import('/src/services/appTooltipPolicy.ts')
    window.removeTooltipPolicy = installAppTooltipPolicy()
  })
  const tooltip = page.locator('#longedit-app-tooltip')
  const create = page.getByTestId('library-create-menu')
  const assertHidden = async () => {
    assert.equal(await tooltip.getAttribute('aria-hidden'), 'true')
    assert.equal(await tooltip.evaluate(element => getComputedStyle(element).visibility), 'hidden')
  }
  const waitClosed = () => page.waitForFunction(() => document.body.dataset.appPopupOpen === 'false')
  const assertNoDocumentHint = async target => {
    assert.equal(await target.getAttribute('title'), null)
    assert.equal(await target.getAttribute('data-app-tooltip'), null)
    await target.hover()
    await page.waitForTimeout(550)
    await assertHidden()
    assert.equal(await page.locator('.workspace-tab-tooltip').count(), 0)
    assert.equal(await page.locator('.n-tooltip:visible').count(), 0)
  }
  for (const [theme, style] of [['white', 'soft'], ['dark', 'glass']]) {
    await page.evaluate(({ theme, style }) => {
      window.workflowAudit.store.theme = theme
      window.workflowAudit.store.visualStyle = style
    }, { theme, style })
    await assertNoDocumentHint(page.locator('.workspace-tab.active'))
    await assertNoDocumentHint(page.locator('.workspace-tab:not(.active)').first())
    await assertNoDocumentHint(page.locator('.document-breadcrumb'))
    await page.screenshot({ path: `${output}/${theme}-document-name-no-hint.png`, animations: 'disabled' })
    await create.hover()
    await page.waitForFunction(() => document.querySelector('#longedit-app-tooltip').dataset.visible === 'true')
    assert.equal(await create.getAttribute('title'), null)
    await page.screenshot({ path: `${output}/${theme}-hover.png`, animations: 'disabled' })
    await create.click()
    await page.locator('.library-create-dropdown-menu').waitFor()
    await page.waitForFunction(() => document.body.dataset.appPopupOpen === 'true')
    await assertHidden()
    await page.waitForTimeout(600)
    await assertHidden()
    await page.screenshot({ path: `${output}/${theme}-menu.png`, animations: 'disabled' })
    const item = page.locator('.library-create-dropdown-menu .n-dropdown-option').first()
    assert.equal(await item.evaluate(element => {
      const rect = element.getBoundingClientRect()
      return element.contains(document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2))
    }), true)
    await page.mouse.click(800, 650)
    await waitClosed()
    await page.mouse.move(800, 500)
  }
  checks.push('Hover hints remain available; light and dark dropdowns dismiss them immediately and keep them hidden while open')
  checks.push('Active and inactive document tabs and the current filename show no hover popup in light and dark styles')

  // Click before the delayed hover hint has fired, then remain on the trigger.
  await create.hover()
  await create.click()
  await page.waitForTimeout(600)
  await assertHidden()
  await page.mouse.click(800, 650)
  await waitClosed()
  checks.push('A quick click cancels pending hover/focus hint timers')

  const mode = page.locator('.inline-mode')
  await mode.evaluate(element => element.setAttribute('aria-describedby', 'existing-description'))
  await mode.focus()
  await page.waitForFunction(() => document.querySelector('#longedit-app-tooltip').dataset.visible === 'true')
  assert.match(await mode.getAttribute('aria-describedby'), /existing-description longedit-app-tooltip/)
  await mode.press('Enter')
  await page.locator('.n-dropdown-menu').getByText('源码编辑', { exact: true }).waitFor()
  await assertHidden()
  assert.equal(await mode.getAttribute('aria-describedby'), 'existing-description')
  await page.keyboard.press('Escape')
  await waitClosed()
  checks.push('Keyboard activation dismisses the hint and restores the original accessible description')

  const width = page.locator('.inline-width')
  await width.hover()
  await page.waitForFunction(() => document.querySelector('#longedit-app-tooltip').dataset.visible === 'true')
  await width.click()
  await page.locator('.n-dropdown-menu').getByText('窄栏 600px', { exact: true }).click()
  await waitClosed()
  assert.match(await width.innerText(), /窄栏/)
  await page.mouse.move(800, 500)
  await width.hover()
  await page.waitForFunction(() => document.querySelector('#longedit-app-tooltip').dataset.visible === 'true')
  checks.push('Dropdown selection still works; hints return on the next hover after closing')

  await page.getByTestId('library-document-menu').click()
  await page.locator('.document-menu-content').waitFor()
  await create.hover()
  await page.waitForTimeout(600)
  await assertHidden()
  await assertNoDocumentHint(page.locator('.workspace-tab.active'))
  await page.mouse.click(800, 650)
  await waitClosed()
  await assertNoDocumentHint(page.locator('.workspace-tab.active'))
  assert.equal(await page.locator('body').getAttribute('data-app-popup-open'), 'false')
  checks.push('Document action popovers take priority over application hints; document tabs stay free of popups before and after closing')

  const firstPath = await page.evaluate(() => window.workflowAudit.store.activeTabId)
  const secondTab = page.locator('.workspace-tab:not(.active)').first()
  await secondTab.click()
  await page.waitForFunction(firstPath => window.workflowAudit.store.activeTabId !== firstPath, firstPath)
  await page.waitForFunction(() => document.querySelector('.document-breadcrumb')?.textContent.includes('会议记录.md'))
  await page.locator('.workspace-tab.active').focus()
  await page.waitForTimeout(120)
  await assertHidden()
  await page.keyboard.press('ArrowLeft')
  await page.waitForFunction(firstPath => window.workflowAudit.store.activeTabId === firstPath, firstPath)
  await page.locator('.document-breadcrumb').focus()
  await page.waitForTimeout(120)
  await assertHidden()
  await page.keyboard.press('Enter')
  await page.locator('.rename-editor').waitFor()
  assert.equal(await page.locator('#library-rename-input input').inputValue(), '项目方案.md')
  await page.locator('.n-dialog').getByRole('button', { name: '取消', exact: true }).click()
  await page.locator('.rename-editor').waitFor({ state: 'hidden' })
  await page.locator('.workspace-tab:not(.active) .close-tab').click()
  assert.equal(await page.locator('.workspace-tab').count(), 1)
  assert.equal(await page.evaluate(() => window.workflowAudit.store.activeTabId), firstPath)
  checks.push('Tab switching, arrow-key navigation, filename rename entry and closing an inactive tab remain usable without hints')

  const more = page.locator('#vditor-lib [data-type="more"]')
  await more.hover()
  await more.click()
  await page.waitForFunction(() => document.body.dataset.appPopupOpen === 'true')
  assert.equal(await more.evaluate(element => getComputedStyle(element, '::after').display), 'none')
  await page.screenshot({ path: `${output}/format-menu.png`, animations: 'disabled' })
  await more.click()
  await waitClosed()
  checks.push('Vditor format menus suppress their own CSS tooltip while expanded')

  await page.locator('.library-file-tree').getByText('会议记录.md', { exact: true }).click({ button: 'right' })
  await page.locator('.n-dropdown-menu').getByText('编辑显示样式', { exact: true }).waitFor()
  await create.hover()
  await page.waitForTimeout(600)
  await assertHidden()
  await page.mouse.click(800, 650)
  await waitClosed()
  checks.push('Manual context menus use the same hint suppression')

  await page.evaluate(async () => {
    const { default: SettingsView } = await import('/src/views/SettingsView.vue')
    window.workflowAudit.router.addRoute({ path: '/settings', name: 'Settings', component: SettingsView })
  })
  await page.getByRole('link', { name: '设置', exact: true }).click()
  await page.getByRole('navigation', { name: '设置分类' }).getByRole('button', { name: '外观', exact: true }).click()
  const font = page.locator('.n-select[aria-label="正文字体"]')
  // The actual select usually has a text label; add a hint to exercise the
  // global title contract on Naive UI's reusable selection popup.
  await font.scrollIntoViewIfNeeded()
  await page.waitForTimeout(150)
  await font.evaluate(element => element.setAttribute('title', '选择正文字体'))
  await font.hover()
  await page.waitForFunction(() => document.querySelector('#longedit-app-tooltip').dataset.visible === 'true')
  await font.click()
  await page.locator('.n-base-select-menu').waitFor()
  await page.waitForTimeout(600)
  await assertHidden()
  await page.screenshot({ path: `${output}/select-menu.png`, animations: 'disabled' })
  await page.keyboard.press('Escape')
  await waitClosed()
  checks.push('Reusable select lists suppress hints while open and release suppression when closed')

  await page.evaluate(() => window.removeTooltipPolicy())
  assert.equal(await tooltip.count(), 0)
  assert.equal(await page.locator('body').getAttribute('data-app-popup-open'), null)
  assert.deepEqual(errors, [])
  assert.deepEqual(await page.evaluate(() => window.workflowAudit.calls.filter(call => call.command.startsWith('write_') || call.command === 'ai_chat_completion')), [])
  await fs.writeFile(`${output}/results.json`, JSON.stringify({ checks, errors, scope: 'Production App, LibraryMode, Vditor, SettingsView and tooltip policy; mock native IPC. No document writes.' }, null, 2) + '\n')
  console.log(JSON.stringify({ checks, errors }))
} finally { await browser.close() }
