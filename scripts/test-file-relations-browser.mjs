import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
const { chromium } = createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = process.env.LONGEDIT_BROWSER_EVIDENCE_DIRECTORY || 'docs/evidence/v112-sidebar-density/file-relations'
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.LONGEDIT_BROWSER_CHANNEL || undefined, headless: true })
const checks = [], errors = [], layouts = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
  page.setDefaultTimeout(12000); page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/file-relations-browser.html')
  await page.getByText('显示 1 / 1 行', { exact: true }).waitFor()
  await page.evaluate(() => { window.fileRelationsAudit.store.theme = 'dark'; window.fileRelationsAudit.store.visualStyle = 'soft' })
  const trigger = page.getByTestId('library-add-relation')
  assert.equal(await trigger.isDisabled(), false)
  const order = await trigger.evaluate(el => ({ previous: el.previousElementSibling.dataset.testid, x: el.getBoundingClientRect().x, beforeX: el.previousElementSibling.getBoundingClientRect().x }))
  assert.equal(order.previous, 'library-focus-toggle'); assert.ok(order.x > order.beforeX)
  await page.locator('.document-toolbar').screenshot({ path: output+'/01-toolbar-table-dark.png' })
  await trigger.click()
  const dialog = page.locator('.file-relation-dialog')
  await dialog.waitFor()
  const choose = async (field, name) => {
    await dialog.locator('.relation-file-picker .n-select').nth(field).click()
    await page.locator('.n-base-select-option:visible').filter({ hasText: name }).click()
    await dialog.locator('select').click()
  }
  assert.ok((await dialog.locator('.relation-file-picker').first().textContent()).includes('测试结果.csv'))
  await choose(1, '依据.pdf')
  await dialog.getByRole('combobox', { name: '资料关系类型', exact: true }).selectOption('cites')
  await dialog.getByRole('textbox', { name: '补充说明（可不填）', exact: true }).fill('这份 PDF 提供测试结果的参考依据')
  await dialog.screenshot({ path: output+'/02-add-table-pdf-dark.png' })
  await page.evaluate(() => { window.fileRelationsAudit.failSave = true })
  await dialog.getByRole('button', { name: '添加关系', exact: true }).click()
  await dialog.getByText('关系没有保存成功，所选文件和说明已保留，请重试。', { exact: true }).waitFor()
  assert.equal(await dialog.getByRole('textbox', { name: '补充说明（可不填）', exact: true }).inputValue(), '这份 PDF 提供测试结果的参考依据')
  await page.evaluate(() => { window.fileRelationsAudit.failSave = false })
  await dialog.getByRole('button', { name: '添加关系', exact: true }).click()
  await dialog.getByText('关系已保存，可以继续添加或返回阅读。', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: '添加关系', exact: true }).click()
  await page.waitForFunction(() => window.fileRelationsAudit.records.length === 1)
  await dialog.locator('.existing-relations > summary').click()
  await dialog.locator('.existing-relations article').waitFor()
  assert.equal(await dialog.locator('.existing-relations article').count(), 1)
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  checks.push('The common editor action sits next to Focus for an actual CSV editor; choosing PDF, relation type and note saves through the shared dialog, failure retains the inputs and repeated save keeps one record')

  await page.locator('#tab-links').click()
  const relationPanel = page.getByRole('region', { name: '笔记关系', exact: true })
  await relationPanel.getByRole('button', { name: '添加资料关系', exact: true }).click()
  await dialog.waitFor()
  await choose(0, '图片.png')
  await choose(1, '配置.json')
  await dialog.getByRole('button', { name: '添加关系', exact: true }).click()
  await dialog.getByText('关系已保存，可以继续添加或返回阅读。', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.fileRelationsAudit.records.length), 2)
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await page.evaluate(() => window.fileRelationsAudit.router.push({ name: 'Graph' }))
  await page.locator('.graph-container canvas').first().waitFor()
  const search = page.getByPlaceholder('搜索节点')
  await search.fill('测试结果.csv'); await search.press('Enter')
  await page.locator('.node-details').getByRole('button', { name: '为这份资料添加关系', exact: true }).waitFor()
  assert.ok((await page.locator('.node-details').textContent()).includes('参考'))
  await page.locator('.node-details').screenshot({ path: output+'/03-table-relations-graph-dark.png', animations: 'disabled' })
  await page.getByRole('button', { name: '如何关联资料', exact: true }).click()
  await page.locator('.tutorial-card').waitFor()
  assert.ok((await page.locator('.tutorial-card').textContent()).includes('笔记、PDF、表格、图片'))
  assert.equal(await page.locator('.tutorial-card details').evaluate(el => el.open), false)
  await page.locator('.tutorial-card').screenshot({ path: output+'/04-graph-guide-dark.png', animations: 'disabled' })
  await page.getByRole('button', { name: '现在添加关系', exact: true }).click()
  await dialog.waitFor()
  assert.ok((await dialog.locator('.relation-file-picker').first().textContent()).includes('测试结果.csv'))
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await page.locator('.node-details').getByRole('button', { name: '移除手动关系', exact: true }).click()
  await page.waitForFunction(() => window.fileRelationsAudit.records.length === 1)
  await search.fill('图片.png'); await search.press('Enter')
  await page.locator('.node-details').getByRole('button', { name: '为这份资料添加关系', exact: true }).click()
  await dialog.waitFor()
  await dialog.locator('.existing-relations > summary').click()
  await dialog.getByRole('button', { name: '移除与 配置.json 的关系', exact: true }).click()
  await page.waitForFunction(() => window.fileRelationsAudit.records.length === 0)
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  checks.push('The compact sidebar exposes adding relations for a CSV directly; Image/JSON relationships save from this entry, and the graph supports creation, immediate refresh and removal')

  for (const style of ['soft', 'neo', 'glass', 'airy', 'minimal', 'sharp']) {
    for (const width of [1280, 480]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.evaluate(style => { window.fileRelationsAudit.store.visualStyle = style; window.fileRelationsAudit.store.theme = style === 'glass' ? 'dark' : 'green' }, style)
      await page.waitForFunction(style => document.body.dataset.style === style, style)
      await page.getByTestId('graph-add-relation').click()
      await dialog.waitFor()
      await choose(1, '其他附件.xyz')
      const layout = await dialog.evaluate(el => ({ style: document.body.dataset.style, width: innerWidth, overflow: el.scrollWidth > el.clientWidth, bodyOverflow: el.querySelector('.relation-dialog-body').scrollWidth > el.querySelector('.relation-dialog-body').clientWidth, radius: getComputedStyle(el).borderRadius }))
      assert.equal(layout.overflow, false); assert.equal(layout.bodyOverflow, false); layouts.push(layout)
      assert.ok(await dialog.getByRole('button', { name: '添加关系', exact: true }).isVisible())
      await dialog.getByRole('button', { name: '完成', exact: true }).click()
    }
  }
  assert.ok(new Set(layouts.map(layout => layout.radius)).size >= 4)
  await page.setViewportSize({ width: 1280, height: 1000 })
  await page.getByTestId('graph-add-relation').click()
  await dialog.waitFor(); await choose(1, '其他附件.xyz')
  await dialog.screenshot({ path: output+'/05-any-file-green.png' })
  checks.push('The graph entry remains visible at narrow widths, arbitrary attachment types remain selectable and six styles fit the dialog without horizontal overflow')
  assert.equal(await page.evaluate(() => window.fileRelationsAudit.calls.some(call => /^(write_|update_graph_relation$)/.test(call.command))), false)
  assert.deepEqual(errors, [])
  await fs.writeFile(output+'/results.json', JSON.stringify({ checks, layouts, errors, scope: 'Actual App/LibraryMode/TableView/GraphView and relation dialog; isolated catalog/persistence/graph replies. Native persistence and graph merge tested separately on real files.' }, null, 2))
  console.log(JSON.stringify({ checks, layouts: layouts.length, errors }, null, 2))
} finally { await browser.close() }
