import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve('docs/evidence/v110-workbook-freeze-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workbook-save-browser.html')
  await page.locator('.workbook-cell').first().click()
  await page.keyboard.press('ArrowDown')
  await page.locator('.tool-panel-trigger').click()
  await page.getByText('单元格格式', { exact: true }).click()
  await page.getByTitle('冻结当前单元格上方行和左侧列', { exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingFreeze)
  assert.equal(await page.locator('input[placeholder="当前单元格不可编辑"]').isDisabled(), true)
  await page.screenshot({ path: path.join(output, '01-freeze-pending.png') })
  await page.evaluate(() => window.workbookAudit.pendingFreeze(true))
  await page.getByText('tasks.xlsx 冻结窗格保存失败：模拟冻结写入失败', { exact: true }).waitFor()
  assert.equal(await page.getByTitle('取消当前工作表冻结窗格', { exact: true }).isDisabled(), true)
  await page.getByTitle('冻结当前单元格上方行和左侧列', { exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingFreeze)
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet2' }).click()
  await page.getByText('第二张表的客户清单', { exact: true }).waitFor()
  await page.evaluate(() => window.workbookAudit.pendingFreeze(false))
  await page.getByText('冻结窗格已更新', { exact: true }).waitFor()
  assert.equal((await page.locator('.sheet-tabs button.active').innerText()).trim(), 'Sheet2')
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet1' }).click()
  const clear = page.getByTitle('取消当前工作表冻结窗格', { exact: true })
  await clear.waitFor(); assert.equal(await clear.isEnabled(), true)
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  await page.screenshot({ path: path.join(output, '02-freeze-restored.png') })
  await clear.click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingFreeze)
  await page.evaluate(() => window.workbookAudit.pendingFreeze(false))
  await page.getByText('冻结窗格已取消', { exact: true }).waitFor()
  assert.equal(await clear.isDisabled(), true)
  assert.deepEqual(errors, [])
  console.log('PASS: actual freeze pending/failure/retry/sheet switch/clear; simulated IPC only')
} finally { await browser.close() }
