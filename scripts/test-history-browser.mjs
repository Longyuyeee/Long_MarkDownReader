import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const out = path.resolve(process.env.LONGEDIT_HISTORY_EVIDENCE_DIR || 'docs/evidence/v110-history-ownership')
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  page.setDefaultTimeout(10000)
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/history-browser.html')
  await page.waitForFunction(() => window.historyAudit?.pending.length > 0)
  await page.locator('#tab-history').click()
  await page.evaluate(() => { window.historyAudit.store.activateTab('C:/audit/B.md') })
  await page.waitForFunction(() => window.historyAudit.pending.some(item => item.path.endsWith('/B.md')))
  await page.evaluate(() => {
    for (const item of window.historyAudit.pending.filter(item => item.path.endsWith('/B.md'))) item.resolve([[1, 'B 的历史版本']])
  })
  await page.locator('.history-bubble').filter({ hasText: 'B 的历史版本' }).waitFor()
  await page.evaluate(() => {
    for (const item of window.historyAudit.pending.filter(item => item.path.endsWith('/A.md'))) item.resolve([[1, 'A 的迟到历史，不应显示']])
  })
  await page.waitForTimeout(150)
  assert.equal(await page.locator('.history-bubble').count(), 1)
  assert.equal(await page.getByText('A 的迟到历史，不应显示').count(), 0)
  await page.screenshot({ path: path.join(out, '01-current-file-history.png') })
  await page.locator('.history-bubble').click()
  await page.getByText('历史差异与恢复', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/B.md')).content), 'B 当前正文')
  await page.screenshot({ path: path.join(out, '04-compare-before-restore.png') })
  await page.setViewportSize({ width: 640, height: 800 })
  await page.screenshot({ path: path.join(out, '05-compare-narrow.png') })
  assert.equal(await page.getByLabel('版本差异').evaluate(el => el.scrollWidth > el.clientWidth), false)
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.getByRole('button', { name: '替换编辑区…', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).last().click()
  await page.getByText('替换当前编辑区？', { exact: true }).waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/B.md')).content), 'B 当前正文')
  await page.evaluate(() => { window.historyAudit.failProtection = true })
  await page.getByRole('button', { name: '替换编辑区…', exact: true }).click()
  await page.getByRole('button', { name: '保护草稿并替换', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: /草稿保护写入失败/ }).waitFor()
  await page.getByText('替换当前编辑区？', { exact: true }).waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/B.md')).content), 'B 当前正文')
  await page.evaluate(() => { window.historyAudit.failProtection = false })
  await page.getByRole('button', { name: '替换编辑区…', exact: true }).click()
  await page.getByRole('button', { name: '保护草稿并替换', exact: true }).click()
  await page.getByText('历史内容已载入编辑区，尚未保存到文件', { exact: true }).waitFor()
  await page.waitForFunction(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/B.md')).content.includes('B 的历史版本'))
  assert.equal(await page.evaluate(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/A.md')).content), 'A 当前正文')
  assert.equal(await page.evaluate(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/B.md')).isDirty), true)
  assert.equal(await page.evaluate(() => window.historyAudit.calls.some(c => /^(save_text_document|write_file)$/.test(c.command))), false)
  assert.equal(await page.evaluate(() => window.historyAudit.calls.filter(c => c.command === 'prepare_history_restore').length), 2)
  await page.screenshot({ path: path.join(out, '02-restored-draft.png') })
  await page.evaluate(() => {
    window.historyAudit.store.tabs.push({ id: 'C:/audit/missing.md', path: 'C:/audit/missing.md', title: 'missing.md', isDirty: false })
    window.historyAudit.store.activateTab('C:/audit/missing.md')
  })
  await page.waitForFunction(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/missing.md')).textReadOnlyReason)
  assert.equal(await page.getByRole('button', { name: '继续加载', exact: true }).count(), 0)
  await page.getByText('读取失败 · 只读', { exact: true }).waitFor()
  assert.equal(await page.locator('#vditor-lib [contenteditable="true"]').evaluateAll(elements => elements.filter(element => element.getClientRects().length > 0).length), 0)
  assert.equal(await page.locator('#vditor-lib').innerText().then(text => text.includes('B 的历史版本')), false)
  assert.equal(await page.evaluate(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('/B.md')).content.includes('B 的历史版本')), true)
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(out, '03-missing-file-safe.png') })
  await page.evaluate(() => { window.historyAudit.store.activateTab('C:/audit/B.md') })
  await page.waitForFunction(() => window.historyAudit.pending.filter(item => item.path.endsWith('/B.md')).length >= 3)
  await page.evaluate(() => { for (const item of window.historyAudit.pending.filter(item => item.path.endsWith('/B.md'))) item.resolve([[1, 'B 的历史版本']]) })
  await page.waitForTimeout(150) // Vditor commits the switched document after its delayed layout pass.
  await page.locator('.history-bubble').click()
  await page.getByRole('button', { name: '恢复为副本', exact: true }).click()
  await page.waitForFunction(() => window.historyAudit.store.activeTabId === 'C:/audit/B-恢复-1-1.md')
  await page.waitForFunction(() => window.historyAudit.store.tabs.find(t => t.path.endsWith('B-恢复-1-1.md'))?.content === 'B 的历史版本')
  assert.equal(await page.evaluate(() => window.historyAudit.store.tabs.find(t => t.path === 'C:/audit/B.md').isDirty), true)
  assert.equal(await page.evaluate(() => window.historyAudit.calls.some(c => c.command === 'save_text_document')), false)
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(out, '06-copy-opened-in-editor.png') })
  assert.deepEqual(errors, [])
  console.log('PASS: actual LibraryMode comparison, cancellation, failed protection, protected draft replacement, safe missing-file UI and reopened copy; simulated IPC')
} finally { await browser.close() }
