import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { mobileCodeFormats as formats } from '../shared/mobile-code-formats.ts'

const check = process.argv.includes('--check'), extensions = formats.flatMap(f => [...f.extensions])
const aliases = formats.flatMap(f => [f.mime, ...f.aliases])
assert.equal(new Set(extensions).size, extensions.length, 'Extensions must be unique')
assert.equal(new Set(aliases).size, aliases.length, 'MIME aliases must be unambiguous')
for (const ext of extensions) assert.match(ext, /^[a-z][a-z0-9]*$/)
for (const mime of aliases) assert.match(mime, /^[a-z]+\/[a-z0-9.+-]+$/)
const fingerprint = createHash('sha256').update(JSON.stringify(formats)).digest('hex')
const quote = value => JSON.stringify(value)
const entries = values => values.map(([key, value]) => `        ${quote(key)} to ${quote(value)}`).join(',\n')
const kotlin = `package com.longyuye.longedit.storage

// Generated by scripts/generate-mobile-code-formats.mjs; registry SHA-256: ${fingerprint}
// Source identities only. These MIME types never grant code execution.
object CodeFiles {
    private val extensionMimes = mapOf(
${entries(formats.flatMap(f => f.extensions.map(ext => [ext, f.mime])))}
    )
    private val mimeDefaults = mapOf(
${entries(formats.flatMap(f => [f.mime, ...f.aliases].map(mime => [mime, f.extensions[0]])))}
    )
    val mimes = mimeDefaults.keys.toList()
    fun supports(path: String) = extensionMimes.containsKey(path.substringAfterLast('.', "").lowercase())
    fun extension(path: String): String? = path.substringAfterLast('.', "").lowercase().takeIf { extensionMimes.containsKey(it) }?.let { ".$it" }
    fun mime(path: String): String? = extensionMimes[path.substringAfterLast('.', "").lowercase()]
    fun defaultName(mime: String?, base: String = "导入源码"): String? {
        val type = mime?.substringBefore(';')?.trim()?.lowercase() ?: return null
        val ext = mimeDefaults[type] ?: return null
        return "$base.$ext"
    }
}
`
const marker = /                <!-- Mobile source MIME types start -->[\s\S]*?                <!-- Mobile source MIME types end -->/g
const manifestPath = 'src-tauri/gen/android/app/src/main/AndroidManifest.xml'
const manifest = readFileSync(manifestPath, 'utf8').replaceAll('\r\n', '\n')
assert.equal([...manifest.matchAll(marker)].length, 2, 'Both VIEW and SEND source blocks must exist')
const block = '                <!-- Mobile source MIME types start -->\n' + aliases.map(mime => `                <data android:mimeType="${mime}" />`).join('\n') + '\n                <!-- Mobile source MIME types end -->'
const outputs = [
  ['src-tauri/plugins/mobile-storage/android/src/main/java/CodeFiles.kt', kotlin],
  [manifestPath, manifest.replace(marker, block)]
]
for (const [file, expected] of outputs) {
  if (check) assert.equal(readFileSync(file, 'utf8').replaceAll('\r\n', '\n'), expected, `Stale mobile source metadata: ${file}`)
  else writeFileSync(file, expected)
}
console.log(`${check ? 'Checked' : 'Generated'} ${extensions.length} source extensions and ${aliases.length} MIME identities; ${fingerprint}`)
