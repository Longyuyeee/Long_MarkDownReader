import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const out = path.resolve('docs/evidence/v110-inbox-archive-browser')
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 760 } })
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/inbox-archive-browser.html')
  await page.getByRole('button', { name: '会议记录.md', exact: true }).waitFor()
  await page.screenshot({ path: path.join(out, process.argv.includes('--before') ? '00-before.png' : '01-inbox.png') })
  if (!process.argv.includes('--before')) {
    await page.getByRole('checkbox', { name: '选择归档 会议记录.md', exact: true }).check()
    assert.deepEqual(await page.evaluate(() => window.inboxAudit.opened), [])
    await page.getByRole('button', { name: '归档到…（1）', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('目标目录', { exact: true }).fill('C:/audit/项目')
    await dialog.getByRole('button', { name: '检查归档条件', exact: true }).click()
    await dialog.getByText('尚未移动任何文件。预检结果不代表归档完成。', { exact: true }).waitFor()
    assert.equal(await dialog.getByText('未执行', { exact: true }).count(), 1)
    await page.waitForTimeout(300)
    await page.screenshot({ path: path.join(out, '02-blocked-preflight.png') })
    await dialog.getByLabel('目标文件名', { exact: true }).fill('会议记录-整理.md')
    assert.equal(await dialog.getByText('归档预检结果', { exact: true }).count(), 0)
    await dialog.getByRole('button', { name: '检查归档条件', exact: true }).click()
    await dialog.getByText('归档预检结果', { exact: true }).waitFor()
    const calls = await page.evaluate(() => window.inboxAudit.calls)
    assert.equal(calls.filter(item => item.command === 'preflight_archive').at(-1).args.items[0].targetName, '会议记录-整理.md')
    assert.equal(calls.some(item => /move_|execute_/.test(item.command)), false)
    await page.setViewportSize({ width: 360, height: 800 })
    await page.screenshot({ path: path.join(out, '03-narrow-preflight.png') })
    assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), true)
    await dialog.getByRole('button', { name: '关闭', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: '会议记录.md', exact: true }).click()
    assert.equal((await page.evaluate(() => window.inboxAudit.opened)).length, 1)
    await page.setViewportSize({ width: 1100, height: 800 })
    await page.goto('http://127.0.0.1:9000/scripts/fixtures/inbox-archive-browser.html?results=1')
    await page.getByRole('heading', { name: '归档未全部完成', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: '打开文件', exact: true }).count(), 1)
    await page.getByRole('button', { name: '打开文件', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.inboxAudit.opened), ['项目/会议记录.md'])
    await page.getByRole('button', { name: '核对未完成项', exact: true }).click()
    await page.waitForTimeout(300)
    await page.screenshot({ path: path.join(out, '04-partial-results.png') })
    await page.setViewportSize({ width: 360, height: 800 })
    assert.equal(await page.getByRole('dialog').evaluate(element => element.scrollWidth <= element.clientWidth), true)
    await page.screenshot({ path: path.join(out, '05-partial-narrow.png') })
    await page.getByRole('button', { name: '关闭并保留记录', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.inboxAudit.calls.map(item => item.command)), ['read-only-reconcile-requested', 'close-retain-record'])
  }
  console.log('PASS: actual Inbox selection, preflight, rename invalidation, no mutation, narrow layout and normal open')
} finally { await browser.close() }
