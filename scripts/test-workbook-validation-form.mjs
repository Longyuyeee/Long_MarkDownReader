import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import fs from 'node:fs/promises'
const {chromium}=createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE||'playwright')
const output='docs/evidence/v110-workbook-validation-form';await fs.mkdir(output,{recursive:true})
const browser=await chromium.launch(),errors=[]
try{
 const page=await browser.newPage({viewport:{width:480,height:800}})
 page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(10000)
 await page.goto('http://127.0.0.1:9000/scripts/fixtures/workbook-save-browser.html')
 await page.locator('.workbook-cell').first().click()
 await page.locator('.tool-panel-trigger').click();await page.getByText('数据、Table 与规则',{exact:true}).click()
 await page.getByRole('button',{name:'新建验证',exact:true}).click()
 const form=page.locator('.validation-form')
 await form.getByLabel('允许输入',{exact:true}).selectOption('whole')
 await form.getByLabel('值或公式',{exact:true}).fill('0')
 await form.getByLabel('第二个值或公式',{exact:true}).fill('100')
 await form.getByLabel('满足条件',{exact:true}).selectOption('equal')
 assert.equal(await form.getByLabel('第二个值或公式',{exact:true}).count(),0)
 await form.getByLabel('满足条件',{exact:true}).selectOption('between')
 await page.screenshot({path:output+'/01-numeric.png',animations:'disabled'})
 await form.getByRole('button',{name:'取消',exact:true}).click();await form.waitFor({state:'hidden'})
 assert.equal(await page.evaluate(()=>window.workbookAudit.validationWrites.length),0)
 await page.getByRole('button',{name:'新建验证',exact:true}).click()
 await form.getByLabel('选项或单元格区域',{exact:true}).fill('"是,否"')
 await form.getByRole('button',{name:'保存规则',exact:true}).click();await form.waitFor({state:'hidden'})
 await page.waitForFunction(()=>window.workbookAudit.validationWrites.length===1)
 assert.equal(await page.evaluate(()=>window.workbookAudit.validationWrites[0].validation.kind),'list')
 await page.getByRole('button',{name:'编辑验证',exact:true}).click()
 assert.equal(await form.getByLabel('选项或单元格区域',{exact:true}).inputValue(),'"是,否"')
 await form.getByLabel('允许输入',{exact:true}).selectOption('custom')
 assert.equal(await form.getByLabel('验证公式',{exact:true}).inputValue(),'A1<>""')
 await form.getByRole('button',{name:'取消',exact:true}).click();await form.waitFor({state:'hidden'})
 assert.equal(await page.evaluate(()=>window.workbookAudit.validationWrites.length),1)
 await page.screenshot({path:output+'/02-rule-return.png',animations:'disabled'})
 assert.deepEqual(errors,[])
 await fs.writeFile(output+'/results.json',JSON.stringify({checks:['Chinese type/operator selectors','Conditional second value','Cancel no write','List rule IPC payload and readback','Existing rule values','Custom relative default'],scope:'Production WorkbookView, native IPC simulated; not native XLSX acceptance',errors},null,2)+'\n')
 console.log('Workbook validation form checks passed')
}finally{await browser.close()}
