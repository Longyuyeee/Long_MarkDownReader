import fs from 'node:fs'
import crypto from 'node:crypto'
import assert from 'node:assert/strict'
const json = file => JSON.parse(fs.readFileSync(file))
const policy = json('shared/v122-managed-updater-lifecycle-policy.json')
const root = 'docs/evidence/v1.0.22-managed-updater/'
const manifest = json(root + 'import-manifest.json')
assert.equal(policy.status, 'hosted-managed-update-passed')
assert.equal(policy.githubRun.id, manifest.githubRunId)
assert.equal(policy.githubRun.conclusion, 'success')
assert.equal(manifest.files.length, 9)
assert.equal(new Set(manifest.files.map(f => f.path)).size, 9)
for (const item of manifest.files) {
  assert.ok(/^[a-z0-9-]+\.(json|jpg)$/.test(item.path))
  const bytes = fs.readFileSync(root + item.path)
  assert.equal(bytes.length, item.bytes)
  assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), item.sha256)
  if (item.path.endsWith('.jpg')) assert.equal(item.visuallyReviewed, true)
}
const result = json(root + 'managed-updater-lifecycle-result.json')
assert.equal(result.status, 'passed')
assert.equal(result.previousVersion, '1.0.21')
assert.equal(result.currentVersion, '1.0.22')
assert.equal(result.checksPassed, 12)
assert.equal(result.checksFailed, 0)
assert.equal(result.checks.length, 12)
assert.ok(result.checks.every(c => c.status === 'passed'))
assert.equal(result.currentInstallerSha256, policy.releases.current.installer.sha256)
assert.equal(result.installedExecutableSha256, policy.releases.current.installedPackageExecutable.sha256)
assert.equal(result.taggedCommit, policy.releases.current.taggedCommit)
assert.equal(result.automaticRelaunchAfterInstall, true)
assert.equal(result.userDataRetainedAfterOverwrite, true)
assert.equal(result.userDataRetainedAfterUninstall, true)
assert.equal(result.sourceUserContentIncluded, false)
const discovery = json(root + 'managed-updater-discovery-evidence.json')
assert.equal(discovery.confirmation.installerStartedBeforeConfirmation, false)
assert.equal(discovery.confirmation.clicked, true)
assert.equal(discovery.release.latestVersion, '1.0.22')
assert.ok(discovery.release.releaseNotes.includes('搜索可靠性补丁'))
assert.equal(json('shared/v1-community-release-policy.json').patchValidation.managedUpdaterUpgradePath, '1.0.21-to-1.0.22-passed')
assert.equal(json('docs/evidence/v1.0.22-release/release-receipt.json').managedUpdaterObservation, '1.0.21-to-1.0.22-passed')
console.log('Official v1.0.21 to v1.0.22 update accepted: 12 checks and nine immutable reviewed evidence files.')
