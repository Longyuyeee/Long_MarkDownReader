import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve(process.env.LONGEDIT_TABLE_AUDIT_OUTPUT || 'docs/evidence/v110-table-save-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 720 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto((process.env.LONGEDIT_TEST_BASE_URL || 'http://127.0.0.1:9000') + '/scripts/fixtures/table-save-browser.html')
  const cells = page.locator('.data-cell input')
  await cells.first().waitFor()
  await page.screenshot({ path: path.join(output, '01-before.png') })
  await cells.first().fill('先确认交付日期')
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await cells.nth(1).fill('保存时补充客户要求')
  assert.equal(await page.locator('.save-button').innerText(), '保存中')
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '保存')
  assert.equal(await cells.nth(1).inputValue(), '保存时补充客户要求')
  assert.equal(await page.evaluate(() => window.tableAudit.disk.rows[0][1]), '待处理')
  await page.screenshot({ path: path.join(output, '02-new-draft-retained.png') })
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '已保存')
  assert.equal(await page.evaluate(() => window.tableAudit.disk.rows[0][1]), '保存时补充客户要求')
  await page.screenshot({ path: path.join(output, '03-saved.png') })
  await cells.nth(1).fill('失败后还要保留这条备注')
  await page.evaluate(() => { window.tableAudit.failNext = true })
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '保存')
  assert.equal(await cells.nth(1).inputValue(), '失败后还要保留这条备注')
  await page.screenshot({ path: path.join(output, '04-failed-draft-retained.png') })
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '已保存')
  assert.equal(await page.evaluate(() => window.tableAudit.disk.rows[0][1]), '失败后还要保留这条备注')
  // Real route teardown/recreation. Explicitly use the existing discard dialog;
  // this does not claim that unsubmitted drafts survive a deliberate discard.
  for (const fail of [false, true]) {
    const oldValue = await page.evaluate(() => window.tableAudit.disk.rows[0][1])
    const nextValue = fail ? '这次提交模拟失败' : '离开前提交的交付说明'
    await cells.nth(1).fill(nextValue)
    await page.evaluate(value => { window.tableAudit.failNext = value }, fail)
    await page.locator('.save-button').click()
    await page.waitForFunction(() => !!window.tableAudit.pending)
    const reads = await page.evaluate(() => window.tableAudit.reads)
    await page.getByTitle('返回知识库', { exact: true }).click()
    await page.getByRole('button', { name: '放弃修改并离开', exact: true }).click()
    await page.getByRole('button', { name: '重新打开表格', exact: true }).click()
    await page.getByText('正在等待上次保存完成…', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.tableAudit.reads), reads)
    assert.equal(await cells.count(), 0)
    await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
    await page.screenshot({ path: path.join(output, fail ? '06-waiting-failed-save.png' : '05-waiting-save.png') })
    await page.evaluate(() => window.tableAudit.pending())
    await cells.first().waitFor()
    assert.equal(await page.evaluate(() => window.tableAudit.reads), reads + 1)
    assert.equal(await cells.nth(1).inputValue(), fail ? oldValue : nextValue)
  }
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  await page.screenshot({ path: path.join(output, '07-reopened.png') })
  await cells.nth(1).fill('离开等待页后仍完成的提交')
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await page.getByTitle('返回知识库', { exact: true }).click()
  await page.getByRole('button', { name: '放弃修改并离开', exact: true }).click()
  await page.getByRole('button', { name: '重新打开表格', exact: true }).click()
  await page.getByText('正在等待上次保存完成…', { exact: true }).waitFor()
  const abandonedReads = await page.evaluate(() => window.tableAudit.reads)
  await page.getByTitle('返回知识库', { exact: true }).click()
  await page.getByRole('button', { name: '重新打开表格', exact: true }).waitFor()
  await page.evaluate(async () => { window.tableAudit.pending(); await new Promise(resolve => setTimeout(resolve, 50)) })
  assert.equal(await page.evaluate(() => window.tableAudit.reads), abandonedReads)
  assert.equal(await cells.count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: actual TableView headless UI, deferred receipt, retained draft, failure/retry, route recreation and abandoned wait; simulated IPC only')
  console.log(output)
} finally { await browser.close() }
