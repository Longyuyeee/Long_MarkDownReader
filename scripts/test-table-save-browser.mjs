import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve(process.env.LONGEDIT_TABLE_AUDIT_OUTPUT || 'docs/evidence/v110-table-save-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 720 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/table-save-browser.html')
  const cells = page.locator('.data-cell input')
  await cells.first().waitFor()
  await page.screenshot({ path: path.join(output, '01-before.png') })
  await cells.first().fill('先确认交付日期')
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await cells.nth(1).fill('保存时补充客户要求')
  assert.equal(await page.locator('.save-button').innerText(), '保存中')
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '保存')
  assert.equal(await cells.nth(1).inputValue(), '保存时补充客户要求')
  assert.equal(await page.evaluate(() => window.tableAudit.disk.rows[0][1]), '待处理')
  await page.screenshot({ path: path.join(output, '02-new-draft-retained.png') })
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '已保存')
  assert.equal(await page.evaluate(() => window.tableAudit.disk.rows[0][1]), '保存时补充客户要求')
  await page.screenshot({ path: path.join(output, '03-saved.png') })
  await cells.nth(1).fill('失败后还要保留这条备注')
  await page.evaluate(() => { window.tableAudit.failNext = true })
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '保存')
  assert.equal(await cells.nth(1).inputValue(), '失败后还要保留这条备注')
  await page.screenshot({ path: path.join(output, '04-failed-draft-retained.png') })
  await page.locator('.save-button').click()
  await page.waitForFunction(() => !!window.tableAudit.pending)
  await page.evaluate(() => window.tableAudit.pending())
  await page.waitForFunction(() => document.querySelector('.save-button')?.textContent === '已保存')
  assert.equal(await page.evaluate(() => window.tableAudit.disk.rows[0][1]), '失败后还要保留这条备注')
  assert.deepEqual(errors, [])
  console.log('PASS: actual TableView headless UI, deferred receipt, retained draft, failure and retry; simulated IPC only')
  console.log(output)
} finally { await browser.close() }
