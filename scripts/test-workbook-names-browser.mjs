import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve('docs/evidence/v110-workbook-names-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workbook-save-browser.html')
  await page.locator('.workbook-cell').first().click()
  const menu = async label => {
    await page.getByTitle('管理命名区域', { exact: true }).click()
    await page.getByText(label, { exact: true }).click()
  }
  const create = async () => {
    await menu('从当前选区新建名称')
    const dialog = page.getByRole('dialog').filter({ hasText: '创建命名区域' })
    await dialog.locator('input').fill('Delivery')
    await dialog.getByRole('button', { name: '下一步', exact: true }).click()
    const scope = page.getByRole('dialog').filter({ hasText: '命名区域作用域' })
    await scope.getByRole('button', { name: '应用作用域', exact: true }).click()
    await page.waitForFunction(() => !!window.workbookAudit.pendingName)
  }
  await menu('从当前选区新建名称')
  const dialog = page.getByRole('dialog').filter({ hasText: '创建命名区域' })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await create()
  await page.evaluate(() => window.workbookAudit.pendingName(true))
  await page.getByText('tasks.xlsx 命名区域保存失败：模拟名称写入失败', { exact: true }).waitFor()
  await page.getByRole('dialog').filter({ hasText: '命名区域作用域' }).waitFor({ state: 'hidden' })
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '01-name-failure.png') })
  await create()
  await page.locator('.sheet-tabs button').filter({ hasText: 'Sheet2' }).click()
  await page.evaluate(() => window.workbookAudit.pendingName(false))
  await page.getByText('已创建命名区域 Delivery', { exact: true }).waitFor()
  assert.equal((await page.locator('.sheet-tabs button.active').innerText()).trim(), 'Sheet2')
  await menu('重命名当前名称')
  const rename = page.getByRole('dialog').filter({ hasText: '重命名命名区域' })
  await rename.locator('input').fill('DeliveryDate')
  await rename.getByRole('button', { name: '保存名称', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingName)
  await page.evaluate(() => window.workbookAudit.pendingName(false))
  await page.getByText('已将命名区域重命名为 DeliveryDate', { exact: true }).waitFor()
  await menu('删除当前名称')
  const remove = page.getByRole('dialog').filter({ hasText: '删除命名区域 DeliveryDate？' })
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '02-name-delete.png') })
  await remove.getByRole('button', { name: '取消', exact: true }).click()
  await remove.waitFor({ state: 'hidden' })
  await menu('删除当前名称')
  await remove.getByRole('button', { name: '删除名称', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingName)
  await page.evaluate(() => window.workbookAudit.pendingName(false))
  await page.getByText('已删除命名区域 DeliveryDate', { exact: true }).waitFor()
  assert.equal(await page.getByTitle('跳转和管理命名区域').isDisabled(), true)
  assert.deepEqual(errors, [])
  console.log('PASS: name create cancel/failure/retry/sheet switch/rename/delete cancel and confirm; simulated IPC only')
} finally { await browser.close() }
