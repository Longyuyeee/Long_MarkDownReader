import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import fs from 'node:fs/promises'
const {chromium}=createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE||'playwright')
const output=process.env.LONGEDIT_BROWSER_EVIDENCE_DIRECTORY||'docs/evidence/v110-docx-redesign'
await fs.mkdir(output,{recursive:true})
const browser=await chromium.launch(),errors=[],checks=[]
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}})
 page.setDefaultTimeout(12000);page.on('pageerror',error=>errors.push(error.message))
 await page.goto(`${process.env.LONGEDIT_TEST_BASE_URL||'http://127.0.0.1:9000'}/scripts/fixtures/docx-redesign-browser.html`)
 await page.locator('.docx-page').waitFor()
 await page.getByRole('button',{name:'目录与详情',exact:true}).click()
 assert.equal(await page.locator('.docx-outline').isVisible(),false)
 await page.getByRole('button',{name:'目录与详情',exact:true}).click()
 await page.locator('.compatibility-card summary').click()
 await page.getByText('测试夹具',{exact:true}).waitFor()
 await page.screenshot({path:output+'/01-reading.png'})
 checks.push('Directory toggles, full compatibility details expandable, original body and footnote rendered')
 await page.getByLabel('搜索 DOCX 正文').fill('用户')
 assert.equal(await page.locator('.docx-search span').innerText(),'1/1')
 await page.getByTitle('下一个结果',{exact:true}).click()
 await page.getByTitle('打开 DOCX 页面编辑').click()
 const editor=page.locator('.docx-editor')
 await editor.locator('textarea').fill('我想保留这个修改，稍后再保存。')
 await page.getByTitle('关闭编辑面板').click()
 await page.getByTitle('打开 DOCX 页面编辑').click()
 assert.equal(await editor.locator('textarea').inputValue(),'我想保留这个修改，稍后再保存。')
 await page.getByTitle('撤销草稿修改').click()
 await page.getByTitle('重做草稿修改').click()
 assert.equal(await editor.locator('textarea').inputValue(),'我想保留这个修改，稍后再保存。')
 assert.equal(await page.getByTitle('保存到原文件').isDisabled(),true)
 checks.push('Search, editor close/reopen, draft undo/redo and verification-required save preserved')
 await page.screenshot({path:output+'/02-editing.png'})
 for(const width of [900,480]) {
  await page.setViewportSize({width,height:900})
  await page.getByRole('button',{name:'目录与详情',exact:true}).click()
  await page.getByRole('navigation',{name:'DOCX 文档目录'}).getByRole('button').last().click()
  assert.equal(await page.locator('.docx-outline').isVisible(),false)
  await page.getByRole('button',{name:'目录与详情',exact:true}).click()
  await page.screenshot({path:output+`/03-outline-${width}.png`})
  await page.getByRole('button',{name:'关闭目录与详情'}).click()
  assert.equal(await editor.locator('textarea').inputValue(),'我想保留这个修改，稍后再保存。')
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
 }
 checks.push('900px/480px directory remains accessible while editing; navigating and hiding it preserves the draft')
 await page.getByTitle('关闭编辑面板').click()
 await page.evaluate(()=>{document.body.dataset.theme='dark'})
 await page.screenshot({path:output+'/04-dark.png'})
 assert.deepEqual(errors,[])
 const writes=await page.evaluate(()=>window.docxAudit.calls.filter(c=>c.command.startsWith('save_docx')))
 assert.equal(writes.length,0)
 await fs.writeFile(output+'/results.json',JSON.stringify({checks,errors,scope:'Production DOCX Vue component with mocked native parse report; no native parse/save acceptance',releaseCandidate:false},null,2)+'\n')
 console.log(checks.join('\n'))
}finally{await browser.close()}
