import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
const { chromium } = createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = process.env.LONGEDIT_BROWSER_EVIDENCE_DIRECTORY || 'docs/evidence/v116-move-outcome-development/outcomes'
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.LONGEDIT_BROWSER_CHANNEL || undefined, headless: true })
const errors = [], checks = [], layouts = []
const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
page.setDefaultTimeout(15000)
page.on('pageerror', error => errors.push(error.message))
const root = 'C:/workflow-fixture'
const row = path => page.locator(`[data-drop-path="${root}/${path}"]`)
const navigate = async () => {
  await page.goto((process.env.LONGEDIT_TEST_BASE_URL || 'http://127.0.0.1:9000') + '/scripts/fixtures/move-outcome-browser.html')
  await page.evaluate(() => { window.workflowAudit.store.motionSpeed = 'calm' })
  await page.getByRole('link', { name: '资料库', exact: true }).click()
  await row('项目方案.md').waitFor()
}
const selectThree = async () => {
  await row('项目方案.md').click()
  await row('会议记录.md').click({ modifiers: ['Control'] })
  await row('Inbox').click({ modifiers: ['Control'] })
}
const action = async name => { await row('项目方案.md').click({ button: 'right' }); await page.getByText(name, { exact: true }).click() }
const commandCalls = command => page.evaluate(command => window.workflowAudit.outcomeRequests.filter(call => call.command === command), command)
const scenario = command => page.evaluate(command => { window.workflowAudit.outcomeScenario = command; window.workflowAudit.outcomeStep = 0 }, command)
const settle = async () => {
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.waitForFunction(() => !document.getAnimations().some(a => a.playState === 'running' && a.effect?.getTiming().iterations !== Infinity))
}
try {
  await navigate(); await selectThree(); await action('移动到…')
  const transfer = page.locator('.file-operation-dialog').filter({ has: page.getByRole('textbox', { name: '目标文件夹', exact: true }) })
  await transfer.getByRole('textbox', { name: '目标文件夹', exact: true }).fill('交付')
  await scenario('transfer_library_items')
  await transfer.getByRole('button', { name: '移动', exact: true }).click()
  await transfer.getByRole('heading', { name: '需核对 · 1 项', exact: true }).waitFor()
  assert.ok(await transfer.getByRole('heading', { name: '已完成 · 1 项', exact: true }).isVisible())
  assert.ok(await transfer.getByRole('heading', { name: '未执行 · 1 项', exact: true }).isVisible())
  assert.match(await transfer.textContent(), /\.move-stage-isolated-review/)
  await transfer.screenshot({ path: output + '/mixed-move.png' })
  for (const style of ['soft', 'neo', 'glass', 'airy', 'minimal', 'sharp']) for (const width of [1280, 480]) {
    await page.setViewportSize({ width, height: 950 })
    await page.evaluate(style => { window.workflowAudit.store.visualStyle = style; window.workflowAudit.store.theme = style === 'glass' ? 'dark' : 'green' }, style)
    await settle()
    const box = await transfer.boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1)
    assert.equal(await transfer.evaluate(el => el.scrollWidth > el.clientWidth), false)
    assert.ok(await transfer.getByRole('button', { name: '重试未执行的 1 项', exact: true }).isVisible())
    layouts.push({ style, width, fits: true })
    if (style === 'glass' && width === 480) await transfer.screenshot({ path: output + '/mixed-move-glass-narrow.png' })
  }
  await page.setViewportSize({ width: 1280, height: 950 }); await settle()
  await transfer.getByRole('button', { name: '重试未执行的 1 项', exact: true }).click()
  await transfer.getByRole('heading', { name: '已完成 · 2 项', exact: true }).waitFor()
  const calls = await commandCalls('transfer_library_items')
  assert.deepEqual(calls[1].args.paths, [root + '/会议记录.md'])
  assert.equal(await transfer.getByRole('button', { name: /重试/ }).count(), 0)
  assert.ok(await transfer.getByRole('heading', { name: '需核对 · 1 项', exact: true }).isVisible())
  const last = await page.evaluate(async () => (await import('/src/services/libraryFileOperations.ts')).lastLibraryMove.value)
  assert.equal(last.items.length, 2, 'undo retains completed items from both the first request and its safe retry')
  checks.push('Mixed move keeps three explicit outcomes; retries only notExecuted, preserves completed results and review ID, and keeps both successful requests in undo')
  await transfer.getByRole('button', { name: '关闭', exact: true }).click()

  await navigate(); await selectThree(); await action('移动到…')
  await transfer.getByRole('textbox', { name: '目标文件夹', exact: true }).fill('交付')
  await transfer.getByRole('button', { name: '移动', exact: true }).click()
  await transfer.waitFor({ state: 'hidden' })
  await scenario('undo_library_moves')
  const viewport = page.locator('.tree-viewport'), box = await viewport.boundingBox()
  await viewport.click({ button: 'right', position: { x: 6, y: box.height - 8 } })
  await page.getByText('撤销上次移动', { exact: true }).click()
  const feedback = page.locator('.file-operation-dialog').filter({ has: page.getByRole('heading', { name: '需核对 · 1 项', exact: true }) })
  await feedback.waitFor()
  await feedback.getByRole('button', { name: '重试未执行的 1 项', exact: true }).click()
  await feedback.getByRole('heading', { name: '已完成 · 2 项', exact: true }).waitFor()
  const undo = await commandCalls('undo_library_moves')
  assert.equal(undo[1].args.items.length, 1)
  assert.ok(undo[1].args.items[0].newPath.endsWith('/会议记录.md'))
  assert.equal(await feedback.getByRole('button', { name: /重试/ }).count(), 0)
  await feedback.screenshot({ path: output + '/mixed-undo.png' })
  checks.push('Undo retry excludes completed and needsReview paths; final unresolved result stays visible without a repeat button')

  await navigate(); await selectThree(); await action('批量重命名…')
  const rename = page.locator('.batch-rename-dialog')
  await rename.getByRole('textbox', { name: '名称前添加', exact: true }).fill('整理-')
  await page.waitForFunction(() => document.querySelectorAll('.rename-row').length === 3 && !document.querySelector('.rename-preview[aria-busy="true"]'))
  await scenario('rename_library_items')
  await rename.getByRole('button', { name: '重命名 3 项', exact: true }).click()
  await rename.locator('.rename-row.needs-review').waitFor()
  assert.equal(await rename.locator('.rename-row.completed').count(), 1)
  await rename.getByRole('button', { name: '重试未执行的 1 项', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.rename-row.completed').length === 2)
  const renames = await commandCalls('rename_library_items')
  assert.deepEqual(renames[1].args.items.map(item => item.path), [root + '/会议记录.md'])
  await rename.getByRole('textbox', { name: '名称前添加', exact: true }).fill('另一个规则-')
  await page.waitForFunction(() => !document.querySelector('.rename-preview[aria-busy="true"]'))
  assert.equal(await rename.locator('.rename-row.needs-review').count(), 1)
  assert.equal(await rename.locator('.rename-row.completed').count(), 2)
  assert.equal(await rename.getByRole('button', { name: /重试未执行/ }).count(), 0)
  await rename.screenshot({ path: output + '/mixed-rename.png' })
  checks.push('Batch rename preserves completed/review rows across safe retry and rule refresh; only the explicitly not-executed file is submitted again')

  await navigate(); await action('移动到…')
  await transfer.getByRole('textbox', { name: '目标文件夹', exact: true }).fill('交付')
  await scenario('transfer_library_items')
  await page.evaluate(() => { window.workflowAudit.outcomeTransportFailure = true })
  await transfer.getByRole('button', { name: '移动', exact: true }).click()
  await transfer.getByRole('heading', { name: '需核对 · 1 项', exact: true }).waitFor()
  assert.equal(await transfer.getByRole('button', { name: /重试/ }).count(), 0)
  assert.equal((await commandCalls('transfer_library_items')).length, 1)
  assert.ok(await transfer.getByRole('button', { name: '关闭', exact: true }).isEnabled())
  assert.equal(await page.evaluate(() => window.workflowAudit.disk.has('C:/workflow-fixture/项目方案.md')), false)
  assert.equal(await page.evaluate(() => window.workflowAudit.disk.has('C:/workflow-fixture/交付/项目方案.md')), true)
  checks.push('A lost move reply after a simulated commit is unknown, not notExecuted: result stays visible and no automatic/direct retry is offered')

  await navigate(); await action('移动到…')
  await transfer.getByRole('textbox', { name: '目标文件夹', exact: true }).fill('交付')
  await scenario('transfer_library_items')
  await page.evaluate(() => { window.workflowAudit.outcomeLegacyFailure = true })
  await transfer.getByRole('button', { name: '移动', exact: true }).click()
  await transfer.getByRole('heading', { name: '需核对 · 1 项', exact: true }).waitFor()
  assert.equal(await transfer.getByRole('button', { name: /重试/ }).count(), 0)
  checks.push('A move error without an explicit disposition is conservatively needsReview; matching error text or source existence is not treated as retry permission')

  await navigate(); await selectThree(); await action('批量重命名…')
  await rename.getByRole('textbox', { name: '名称前添加', exact: true }).fill('整理-')
  await page.waitForFunction(() => document.querySelectorAll('.rename-row').length === 3 && !document.querySelector('.rename-preview[aria-busy="true"]'))
  await scenario('rename_library_items')
  await page.evaluate(() => { window.workflowAudit.outcomeTransportFailure = true })
  await rename.getByRole('button', { name: '重命名 3 项', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.rename-row.needs-review').length === 3)
  assert.equal(await rename.getByRole('button', { name: /重试未执行/ }).count(), 0)
  assert.ok(await rename.getByRole('button', { name: '刷新预览', exact: true }).isDisabled())
  assert.equal((await commandCalls('rename_library_items')).length, 1)
  checks.push('A lost batch-rename reply leaves all attempted rows for review, disables preview replay and offers no retry')

  await navigate(); await selectThree(); await action('移动到…')
  await transfer.getByRole('textbox', { name: '目标文件夹', exact: true }).fill('交付')
  await transfer.getByRole('button', { name: '移动', exact: true }).click()
  await transfer.waitFor({ state: 'hidden' })
  await scenario('undo_library_moves')
  await page.evaluate(() => { window.workflowAudit.outcomeTransportFailure = true })
  const lastBox = await viewport.boundingBox()
  await viewport.click({ button: 'right', position: { x: 6, y: lastBox.height - 8 } })
  await page.getByText('撤销上次移动', { exact: true }).click()
  const unknownUndo = page.locator('.file-operation-dialog').filter({ has: page.getByRole('heading', { name: '需核对 · 3 项', exact: true }) })
  await unknownUndo.waitFor()
  assert.equal(await unknownUndo.getByRole('button', { name: /重试/ }).count(), 0)
  assert.equal((await commandCalls('undo_library_moves')).length, 1)
  checks.push('A lost undo reply removes attempted items from the direct-undo queue and keeps all three review outcomes visible')

  await navigate(); await action('移动到…')
  await page.evaluate(() => { window.workflowAudit.outcomeChooseFailure = true })
  await transfer.getByRole('button', { name: '选择', exact: true }).click()
  await transfer.getByRole('alert').filter({ hasText: '选择文件夹失败' }).waitFor()
  assert.equal(await transfer.getByRole('heading', { name: /需核对/ }).count(), 0)
  await transfer.getByRole('textbox', { name: '目标文件夹', exact: true }).fill('交付')
  await transfer.getByRole('button', { name: '移动', exact: true }).click()
  await transfer.waitFor({ state: 'hidden' })
  assert.equal((await commandCalls('transfer_library_items')).length, 1)
  checks.push('A folder-picker failure is only a form error, not an unknown file mutation; typing a destination can still complete normally')
  assert.deepEqual(errors, [])
  assert.equal(await page.locator('#runtime-error-notice, #crash-screen').count(), 0)
  await fs.writeFile(output + '/results.json', JSON.stringify({ scope: 'Actual Vue page and normal user clicks, calm motion, isolated native response scenarios; not native filesystem or installed evidence', checks, layouts, errors }, null, 2))
  console.log(JSON.stringify({ checks, layouts: layouts.length, errors }, null, 2))
} catch (error) {
  await page.screenshot({ path: output + '/failure.png' }).catch(() => {})
  await fs.writeFile(output + '/failure.json', JSON.stringify({ error: String(error), errors, checks, text: await page.locator('body').innerText(), calls: await page.evaluate(() => window.workflowAudit.calls.slice(-15)) }, null, 2))
  throw error
} finally { await browser.close() }
