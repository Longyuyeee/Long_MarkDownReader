import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
const { chromium } = createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = 'docs/evidence/v111-tab-switch'
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.LONGEDIT_BROWSER_CHANNEL || undefined, headless: true })
const checks = [], errors = [], transitions = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 860 } })
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/tab-switch-browser.html')
  await page.locator('.data-cell input').first().waitFor()
  await page.waitForFunction(() => !document.querySelector('.table-view').inert)
  const choose = name => page.getByRole('tab', { name, exact: true }).click()
  const release = path => page.evaluate(path => { const a = window.tabSwitchAudit; for (const request of a.pending.get(path) || []) request.resolve(); a.pending.delete(path) }, 'C:/workflow-fixture/' + path)
  const waitRead = path => page.waitForFunction(path => window.tabSwitchAudit.pending.has('C:/workflow-fixture/' + path), path)
  const startSampling = () => page.evaluate(() => {
    window.previousTable = document.querySelector('.table-view'); window.tabSamples = []; window.sampling = true
    const sample = () => {
      const element = document.querySelector('.table-view'), box = element?.getBoundingClientRect()
      window.tabSamples.push({ sameSurface: element === window.previousTable, cells: element?.querySelectorAll('.data-cell input').length || 0, opacity: element ? Number(getComputedStyle(element).opacity) : 0, height: box?.height || 0, busy: element?.inert })
      if (window.sampling) requestAnimationFrame(sample)
    }; requestAnimationFrame(sample)
  })
  for (const style of ['soft', 'neo', 'glass', 'airy', 'minimal', 'sharp']) {
    await page.evaluate(style => { const a = window.tabSwitchAudit; a.store.visualStyle = style; a.store.theme = 'dark'; a.store.motionSpeed = 'calm'; a.hold = true }, style)
    await startSampling()
    await choose('B.table.json'); await waitRead('B.table.json')
    assert.equal(await page.locator('.data-cell input').first().inputValue(), 'A事项0')
    assert.equal(await page.locator('.table-title strong').innerText(), 'A.table.json')
    assert.equal(await page.locator('.table-view').evaluate(el => el.inert), true)
    assert.equal(await page.locator('.table-state').count(), 0)
    await page.waitForTimeout(220)
    await release('B.table.json')
    await page.waitForFunction(() => document.querySelector('.data-cell input')?.value === 'B事项0' && !document.querySelector('.table-view').inert)
    await page.evaluate(() => { window.sampling = false })
    const frames = await page.evaluate(() => window.tabSamples)
    assert.ok(frames.length >= 3)
    assert.ok(frames.every(frame => frame.sameSurface && frame.cells > 0 && frame.opacity === 1 && frame.height > 100))
    transitions.push({ style, frames: frames.length, blankFrames: frames.filter(frame => !frame.cells || !frame.sameSurface).length })
    await choose('A.table.json'); await waitRead('A.table.json'); await release('A.table.json')
    await page.waitForFunction(() => document.querySelector('.data-cell input')?.value === 'A事项0' && !document.querySelector('.table-view').inert)
  }
  checks.push('All six styles retain the exact same table surface and visible cells on every sampled frame while delayed tab reads finish; the old table cannot be edited or saved during the switch')

  await page.locator('.table-scroll').evaluate(el => { el.scrollTop = 380; el.dispatchEvent(new Event('scroll')) })
  await choose('B.table.json'); await waitRead('B.table.json'); await release('B.table.json')
  await page.waitForFunction(() => !document.querySelector('.table-view').inert)
  assert.equal(await page.locator('.table-scroll').evaluate(el => el.scrollTop), 0)
  await choose('A.table.json'); await waitRead('A.table.json'); await release('A.table.json')
  await page.waitForFunction(() => !document.querySelector('.table-view').inert)
  assert.equal(await page.locator('.table-scroll').evaluate(el => el.scrollTop), 380)
  checks.push('Each table keeps its own reading position; a first visit starts at the top and returning restores the previous scroll')

  await choose('B.table.json'); await waitRead('B.table.json')
  await choose('C.csv'); await waitRead('C.csv')
  await release('C.csv')
  await page.waitForFunction(() => document.querySelector('.data-cell input')?.value === 'C事项0' && !document.querySelector('.table-view').inert)
  await release('B.table.json'); await page.waitForTimeout(30)
  assert.equal(await page.locator('.data-cell input').first().inputValue(), 'C事项0')
  checks.push('Rapid A/B/CSV switching discards stale reads and keeps the latest selected file')

  await choose('A.table.json'); await waitRead('A.table.json'); await release('A.table.json')
  await page.waitForFunction(() => !document.querySelector('.table-view').inert)
  await page.locator('.table-scroll').evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')) })
  await page.waitForFunction(() => document.querySelector('.data-cell input')?.value === 'A事项0')
  await page.locator('.data-cell input').first().fill('必须保留的修改')
  await choose('B.table.json')
  await page.getByRole('dialog').getByRole('button', { name: '继续编辑', exact: true }).click()
  assert.equal(await page.locator('.data-cell input').first().inputValue(), '必须保留的修改')
  assert.equal(await page.getByRole('tab', { name: /A.table.json/ }).getAttribute('aria-selected'), 'true')
  await choose('B.table.json')
  await page.getByRole('dialog').getByRole('button', { name: '放弃修改并离开', exact: true }).click()
  await waitRead('B.table.json'); await release('B.table.json')
  await page.waitForFunction(() => document.querySelector('.data-cell input')?.value === 'B事项0' && !document.querySelector('.table-view').inert)
  assert.equal(await page.evaluate(() => window.tabSwitchAudit.writes.length), 0)
  assert.equal(await page.evaluate(() => window.tabSwitchAudit.store.tabs.find(tab => tab.path.endsWith('/A.table.json')).isDirty), false)
  checks.push('Existing unsaved-draft confirmation still cancels navigation without losing content; explicit discard switches without writing the source')

  await choose('C.csv'); await waitRead('C.csv')
  await page.evaluate(() => { for (const request of window.tabSwitchAudit.pending.get('C:/workflow-fixture/C.csv') || []) request.reject(Error('模拟读取失败')); window.tabSwitchAudit.pending.delete('C:/workflow-fixture/C.csv'); window.tabSwitchAudit.hold = false })
  await page.getByText('无法打开表格', { exact: true }).waitFor()
  await page.getByRole('button', { name: '重新加载', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.data-cell input')?.value === 'C事项0')
  checks.push('A failed target still has a real error and working retry instead of leaving old data editable under the new path')

  await page.locator('#tab-quick').click()
  await page.waitForFunction(() => !document.querySelector('.tab-fade-enter-active'))
  await page.evaluate(() => { window.sidebarSamples = []; window.sidebarSampling = true; const sample = () => { window.sidebarSamples.push([...document.querySelectorAll('.sidebar-tab-content > .tab-pane')].some(el => Number(getComputedStyle(el).opacity) > .03)); if (window.sidebarSampling) requestAnimationFrame(sample) }; requestAnimationFrame(sample) })
  await page.locator('#tab-files').click(); await page.waitForTimeout(250)
  await page.evaluate(() => { window.sidebarSampling = false })
  assert.ok((await page.evaluate(() => window.sidebarSamples)).every(Boolean))
  checks.push('Sidebar tabs crossfade with overlapping content rather than fading out to an empty panel before the next one appears')
  await page.screenshot({ path: output + '/table-ready.png' })
  assert.deepEqual(errors, [])
  await fs.writeFile(output + '/results.json', JSON.stringify({ checks, transitions, errors, scope: 'Real App, LibraryMode, WorkspaceTabs and TableView; controlled native read latency in mocked IPC. No installed performance claim.' }, null, 2))
  console.log(JSON.stringify({ checks, transitions, errors }, null, 2))
} finally { await browser.close() }
