import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
const { chromium } = createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = process.env.LONGEDIT_BROWSER_EVIDENCE_DIRECTORY || 'docs/evidence/v113-note-templates'
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, channel: process.env.LONGEDIT_BROWSER_CHANNEL || undefined })
const checks = [], layouts = [], errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 950 } })
  page.setDefaultTimeout(15000); page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/note-templates-browser.html')
  await page.getByRole('link', { name: '资料库', exact: true }).click()
  await page.locator('[data-drop-path="C:/workflow-fixture/项目方案.md"]').click()
  const editor = page.locator('.vditor-wysiwyg [contenteditable="true"]').first()
  await editor.waitFor()
  await editor.click(); await page.keyboard.press('Control+End'); await page.keyboard.type('这是尚未保存的模板段落。')
  await page.getByTestId('library-document-menu').click()
  await page.getByRole('button', { name: '保存为模板…', exact: true }).click()
  const manager = page.locator('.note-template-dialog')
  await manager.waitFor()
  assert.match(await manager.getByRole('textbox', { name: '模板正文', exact: true }).inputValue(), /这是尚未保存的模板段落/)
  checks.push('Save as template captures the active unsaved editor rather than stale disk content')
  await manager.getByRole('textbox', { name: '模板名称', exact: true }).fill('客户沟通')
  const body = '# {{title}}\n日期：{{date}}\n开始：{{time}}\n\n## 待跟进\n- [ ] '
  await manager.getByRole('textbox', { name: '模板正文', exact: true }).fill(body)
  await manager.getByRole('button', { name: '预览填充效果', exact: true }).click()
  const preview = await manager.getByLabel('模板预览').innerText()
  assert.match(preview, /^# 客户沟通\n日期：\d{4}-\d{2}-\d{2}\n开始：\d{2}:\d{2}/)
  await manager.getByRole('button', { name: '返回编辑', exact: true }).click()
  await page.evaluate(() => { window.workflowAudit.failConfig = true })
  await manager.getByRole('button', { name: '保存模板', exact: true }).click()
  await manager.getByRole('alert').waitFor()
  assert.equal(await page.evaluate(() => window.workflowAudit.store.noteTemplates.length), 0)
  assert.equal(await manager.getByRole('textbox', { name: '模板正文', exact: true }).inputValue(), body)
  await page.evaluate(() => { window.workflowAudit.failConfig = false })
  await manager.getByRole('button', { name: '保存模板', exact: true }).click()
  await page.waitForFunction(() => window.workflowAudit.store.noteTemplates.length === 1)
  const id = await page.evaluate(() => window.workflowAudit.store.noteTemplates[0].id)
  checks.push('Variable preview expands title/date/time; a persistence failure keeps input and retries without a duplicate template')
  await manager.locator('#default-note-template').selectOption(id)
  await page.waitForFunction(id => window.workflowAudit.store.defaultNoteTemplates[window.workflowAudit.store.libraryPath] === id, id)
  await manager.getByRole('button', { name: '关闭', exact: true }).click()
  const create = page.getByTestId('library-create-menu')
  await create.click(); await page.getByText('Markdown 笔记 · 客户沟通', { exact: true }).click()
  await page.waitForFunction(() => window.workflowAudit.disk.has('C:/workflow-fixture/客户沟通.md'))
  assert.match(await page.evaluate(() => window.workflowAudit.disk.get('C:/workflow-fixture/客户沟通.md')), /^# 客户沟通\n日期：\d{4}-\d{2}-\d{2}/)
  await create.click(); await page.getByText('笔记模板', { exact: true }).hover()
  await page.locator('.n-dropdown-option-body__label').filter({ hasText: /^客户沟通$/ }).click()
  await page.waitForFunction(() => window.workflowAudit.disk.has('C:/workflow-fixture/客户沟通 1.md'))
  assert.match(await page.evaluate(() => window.workflowAudit.disk.get('C:/workflow-fixture/客户沟通 1.md')), /^# 客户沟通 1\n/)
  await create.click(); await page.getByText('笔记模板', { exact: true }).hover(); await page.getByText('空白笔记', { exact: true }).click()
  await page.waitForFunction(() => window.workflowAudit.disk.has('C:/workflow-fixture/未命名.md'))
  assert.equal(await page.evaluate(() => window.workflowAudit.disk.get('C:/workflow-fixture/未命名.md')), '')
  checks.push('New note uses the library default; explicit template uses unique names, while explicit blank always stays blank')
  const openManager = async () => {
    await create.click(); await page.getByText('笔记模板', { exact: true }).hover()
    await page.getByText('管理模板…', { exact: true }).click(); await manager.waitFor()
  }
  await openManager()
  await manager.getByRole('button', { name: '客户沟通', exact: true }).click()
  await manager.getByRole('textbox', { name: '模板名称', exact: true }).fill('客户沟通记录')
  await manager.getByRole('button', { name: '保存模板', exact: true }).click()
  await page.waitForFunction(() => window.workflowAudit.store.noteTemplates[0].name === '客户沟通记录')
  assert.equal(await manager.locator('#default-note-template').inputValue(), id)
  const savedTemplate = await page.evaluate(() => ({ ...window.workflowAudit.store.noteTemplates[0] }))
  // Observe actual styles at both widths; retain finite user animations and let them finish.
  for (const style of ['soft', 'neo', 'glass', 'airy', 'minimal', 'sharp']) {
    for (const width of [1280, 760]) {
      await page.setViewportSize({ width, height: 950 })
      await page.evaluate(style => { window.workflowAudit.store.visualStyle = style; window.workflowAudit.store.theme = style === 'glass' ? 'dark' : 'green'; window.workflowAudit.store.motionSpeed = 'calm' }, style)
      await page.waitForFunction(() => !document.getAnimations().some(animation => animation.playState === 'running' && animation.effect?.getTiming().iterations !== Infinity))
      await page.waitForFunction(() => !document.querySelector('.n-message'))
      const metrics = await manager.evaluate(element => {
        const r = element.getBoundingClientRect()
        return { left: r.left, right: r.right, bottom: r.bottom, width: innerWidth, height: innerHeight, overflow: element.scrollWidth > element.clientWidth + 1 }
      })
      assert.ok(metrics.left >= 0 && metrics.right <= metrics.width + 1 && metrics.bottom <= metrics.height + 1 && !metrics.overflow, JSON.stringify({ style, width, metrics }))
      layouts.push({ style, width, passed: true })
      if (width === 1280 && ['soft', 'glass'].includes(style)) await page.screenshot({ path: output + '/' + style + '-manager.png' })
    }
  }
  checks.push('Rename preserves the default by ID; template dialogs fit six styles at two widths with normal animations')
  await manager.getByRole('button', { name: '关闭', exact: true }).click()
  await page.evaluate(() => window.workflowAudit.router.push('/quick-note'))
  const capture = page.getByRole('textbox', { name: '笔记正文', exact: true })
  await capture.waitFor()
  await page.waitForFunction(() => document.querySelector('[aria-label="模板"]').value === window.workflowAudit.store.noteTemplates[0].id)
  assert.match(await capture.inputValue(), /^# 客户沟通记录\n日期：\d{4}-\d{2}-\d{2}/)
  await capture.fill('正在写的草稿')
  await page.evaluate(() => { window.workflowAudit.confirmReplace = false })
  await page.getByRole('combobox', { name: '模板', exact: true }).selectOption('builtin:blank')
  assert.equal(await capture.inputValue(), '正在写的草稿')
  await page.evaluate(() => { window.workflowAudit.confirmReplace = true })
  await page.getByRole('combobox', { name: '模板', exact: true }).selectOption('builtin:blank')
  await page.waitForFunction(() => document.querySelector('[aria-label="笔记正文"]').value === '')
  await page.getByRole('combobox', { name: '模板', exact: true }).selectOption(id)
  await page.getByRole('combobox', { name: '保存到', exact: true }).selectOption('C:/workflow-fixture/Inbox')
  await page.getByRole('combobox', { name: '保存后操作', exact: true }).selectOption('continue')
  await page.getByRole('button', { name: '保存笔记', exact: true }).click()
  await page.getByRole('status').filter({ hasText: '已保存：' }).waitFor()
  assert.match(await page.evaluate(() => window.workflowAudit.disk.get('C:/workflow-fixture/Inbox/快速笔记.md')), /^# 客户沟通记录\n/)
  checks.push('Quick note shares custom/default templates, confirms before replacing drafts, saves expanded content and prepares the next note')
  await capture.fill('跨窗口更新时需要保留的草稿')
  await page.evaluate(() => window.workflowAudit.announceTemplates({ noteTemplates: [], defaultNoteTemplates: {} }))
  assert.equal(await capture.inputValue(), '跨窗口更新时需要保留的草稿')
  await page.getByRole('combobox', { name: '模板', exact: true }).getByRole('option', { name: '当前内容（模板已移除）', exact: true }).waitFor({ state: 'attached' })
  checks.push('Cross-window catalog changes refresh available templates without replacing a draft, including a deleted active template')
  await page.setViewportSize({ width: 1280, height: 950 })
  await page.evaluate(saved => {
    const audit = window.workflowAudit
    audit.store.noteTemplates = [saved]
    audit.store.defaultNoteTemplates = { [audit.store.libraryPath]: saved.id }
    return audit.router.push({ name: 'LibraryMode', query: { path: audit.store.activeTabId } })
  }, savedTemplate)
  await openManager()
  await manager.getByRole('button', { name: '客户沟通记录', exact: true }).click()
  await manager.getByRole('button', { name: '删除模板', exact: true }).click()
  await page.getByRole('dialog').filter({ hasText: '删除模板「客户沟通记录」？' }).getByRole('button', { name: '删除模板', exact: true }).click()
  await page.waitForFunction(() => window.workflowAudit.store.noteTemplates.length === 0)
  assert.equal(await manager.locator('#default-note-template').inputValue(), 'builtin:blank')
  assert.deepEqual(await page.evaluate(() => ({ ...window.workflowAudit.store.defaultNoteTemplates })), {})
  assert.equal(await page.evaluate(() => window.workflowAudit.disk.has('C:/workflow-fixture/客户沟通.md')), true)
  checks.push('Deleting a custom template clears its library defaults without stale nested-map entries and keeps existing notes')
  assert.deepEqual(errors, [])
  await fs.writeFile(output + '/report.json', JSON.stringify({ schemaVersion: 1, scope: 'Actual Vue components with simulated native IPC; native filesystem and config serialization tested separately', checks, layouts, errors }, null, 2) + '\n')
  console.log('PASS: ' + checks.length + ' template workflows, ' + layouts.length + ' layouts')
} finally { await browser.close() }
