import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve('docs/evidence/v110-workbook-drawing-edit-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workbook-save-browser.html?drawingEdit=1')
  await page.locator('.tool-panel-trigger').click()
  await page.getByText('图表与绘图对象', { exact: true }).click()
  await page.locator('.drawing-toolbar button').filter({ hasText: '交付进度' }).click()
  const edit = page.getByRole('button', { name: '编辑名称', exact: true })
  await edit.click()
  let dialog = page.getByRole('dialog').filter({ hasText: '绘图对象名称' })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await edit.click()
  await dialog.locator('input').fill('客户交付看板')
  await dialog.getByRole('button', { name: '下一步', exact: true }).click()
  dialog = page.getByRole('dialog').filter({ hasText: '绘图对象替代文本' })
  await dialog.locator('textarea').fill('本周客户交付情况')
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '01-description.png') })
  await dialog.getByRole('button', { name: '保存对象信息', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingDrawing)
  await page.evaluate(() => window.workbookAudit.pendingDrawing(false))
  await page.getByText('已更新绘图对象名称与说明', { exact: true }).waitFor()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.workbookAudit.drawingChange.description), '本周客户交付情况')
  await page.getByRole('button', { name: '应用当前选区', exact: true }).click()
  dialog = page.getByRole('dialog').filter({ hasText: '移动并调整绘图对象？' })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '应用当前选区', exact: true }).click()
  await dialog.getByRole('button', { name: '应用选区', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingDrawing)
  await page.evaluate(() => window.workbookAudit.pendingDrawing(false))
  await page.getByText('已移动并调整绘图对象', { exact: true }).waitFor()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '删除图表', exact: true }).click()
  dialog = page.getByRole('dialog').filter({ hasText: '删除当前图表？' })
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '02-delete.png') })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '删除图表', exact: true }).click()
  await dialog.getByRole('button', { name: '删除图表', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingDrawing)
  await page.evaluate(() => window.workbookAudit.pendingDrawing(false))
  await page.getByText('已删除图表', { exact: true }).waitFor()
  assert.equal(await page.locator('.drawing-toolbar button').filter({ hasText: '交付进度' }).count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: metadata cancel/save, move cancel/confirm, delete cancel/confirm; simulated IPC only')
} finally { await browser.close() }
