import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
const { chromium } = createRequire(import.meta.url)(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = process.env.LONGEDIT_BROWSER_EVIDENCE_DIRECTORY || 'docs/evidence/v112-sidebar-density/inbox'
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.LONGEDIT_BROWSER_CHANNEL || undefined, headless: true })
const checks = [], errors = [], layouts = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 850 } })
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workflow-redesign-browser.html')
  await page.getByRole('link', { name: '资料库', exact: true }).click()
  await page.locator('.library-file-tree').waitFor()
  await page.evaluate(() => {
    const a = window.workflowAudit
    a.directories.splice(0)
    for (const path of a.disk.keys()) if (path.includes('/Inbox/')) a.disk.delete(path)
    a.store.theme = 'green'; a.store.visualStyle = 'soft'
  })
  await page.locator('.inbox-shortcut').click()
  const inbox = page.getByRole('region', { name: '收集箱文件' })
  await inbox.getByText('暂无文件，点击“新建笔记”开始记录。', { exact: true }).waitFor()
  assert.equal(await inbox.getByRole('alert').count(), 0)
  assert.equal(await page.evaluate(() => window.workflowAudit.calls.some(c => c.command === 'create_inbox_directory')), false)
  assert.equal(await inbox.locator('details[open]').count(), 0)
  await inbox.screenshot({ path: output + '/01-empty-green.png' })
  await inbox.getByRole('button', { name: '新建笔记', exact: true }).click()
  await page.waitForFunction(() => window.workflowAudit.store.activeTabId.endsWith('/Inbox/未命名.md'))
  assert.equal(await page.evaluate(() => window.workflowAudit.disk.has('C:/workflow-fixture/Inbox/未命名.md')), true)
  assert.equal(await page.evaluate(() => window.workflowAudit.calls.filter(c => c.command === 'create_new_file').length), 1)
  checks.push('A never-created default inbox is a normal empty state; one deliberate click creates its folder and opens one editable note in that inbox')

  await page.evaluate(() => { window.workflowAudit.directories.splice(window.workflowAudit.directories.indexOf('C:/workflow-fixture/Inbox'), 1) })
  await inbox.getByRole('button', { name: '刷新', exact: true }).click()
  await inbox.getByText('这个文件夹暂时打不开', { exact: true }).waitFor()
  await page.evaluate(() => window.workflowAudit.directories.push('C:/workflow-fixture/Inbox'))
  await inbox.getByRole('button', { name: '重试读取', exact: true }).click()
  await inbox.getByRole('button', { name: /未命名.md/ }).waitFor()
  checks.push('A previously available default inbox that disappears is reported as unavailable rather than as a new empty collection')

  await page.evaluate(() => {
    const a = window.workflowAudit
    a.directories.push('C:/workflow-fixture/Inbox/参考资料')
    a.disk.set('C:/workflow-fixture/Inbox/周会灵感.md', '# 灵感')
    a.disk.set('C:/workflow-fixture/Inbox/参考资料/调研.md', '# 调研')
  })
  await inbox.getByRole('button', { name: '刷新', exact: true }).click()
  await inbox.getByRole('button', { name: /周会灵感.md/ }).waitFor()
  assert.equal(await inbox.locator('.inbox-identity, .inbox-help, .location, .list-summary').count(), 0)
  const listOffset = await inbox.locator('ul').evaluate(el => el.getBoundingClientRect().top - el.closest('.inbox-browser').getBoundingClientRect().top)
  assert.ok(listOffset < 120, `Files start near the toolbar (${listOffset}px), without an introductory screen`)
  checks.push('The root file list starts within 120px of the panel top, without a repeated title, root breadcrumb, tutorial or file-count row')
  await inbox.getByLabel('筛选收集箱文件').fill('周会')
  assert.equal(await inbox.locator('li').count(), 1)
  await inbox.getByLabel('筛选收集箱文件').fill('不存在的搜索')
  await inbox.getByText('没有找到相关文件').waitFor()
  await inbox.locator('.filter-empty').getByRole('button', { name: '清除筛选', exact: true }).click()
  await inbox.getByRole('button', { name: /参考资料/ }).click()
  await inbox.getByRole('button', { name: /调研.md/ }).waitFor()
  await inbox.getByRole('button', { name: '上一级', exact: true }).click()
  await inbox.getByRole('button', { name: /周会灵感.md/ }).waitFor()
  assert.equal(await inbox.locator('li button[title]').count(), 0)
  await inbox.getByRole('button', { name: '收集箱设置', exact: true }).click()
  await inbox.getByRole('button', { name: '更换文件夹…', exact: true }).click()
  await inbox.getByText('已更换保存位置，原有资料留在原文件夹。', { exact: true }).waitFor()
  await inbox.getByRole('button', { name: /调研.md/ }).waitFor()
  assert.equal(await page.evaluate(() => window.workflowAudit.disk.has('C:/workflow-fixture/Inbox/周会灵感.md')), true)
  assert.equal(await page.evaluate(() => window.workflowAudit.calls.some(c => c.command === 'plugin:event|emit' && c.args.event === 'inbox-directory-changed')), true)
  checks.push('File filtering, clear, subfolder/up navigation and choosing a new folder work; previous files stay in place and quick-note windows receive the position change')

  await page.evaluate(() => { window.workflowAudit.directories.splice(window.workflowAudit.directories.indexOf('C:/workflow-fixture/Inbox/参考资料'), 1) })
  await inbox.getByRole('button', { name: '刷新', exact: true }).click()
  await inbox.getByText('这个文件夹暂时打不开', { exact: true }).waitFor()
  await inbox.getByRole('button', { name: '创建文件夹', exact: true }).click()
  await inbox.getByRole('button', { name: /调研.md/ }).waitFor()
  checks.push('A missing custom collection location shows recovery actions and is created only by the explicit create/write action')

  await page.evaluate(() => { window.workflowAudit.failInbox = true; window.workflowAudit.store.theme = 'dark' })
  await inbox.getByRole('button', { name: '刷新', exact: true }).click()
  await inbox.getByText('这个文件夹暂时打不开', { exact: true }).waitFor()
  assert.equal(await inbox.locator('details[open]').count(), 0)
  assert.equal(await page.locator('#crash-screen, #runtime-error-notice').count(), 0)
  await inbox.screenshot({ path: output + '/03-unavailable-dark.png' })
  await inbox.getByRole('button', { name: '新建笔记', exact: true }).click()
  await inbox.locator('.action-error').waitFor()
  assert.equal(await page.evaluate(() => window.workflowAudit.calls.filter(c => c.command === 'create_new_file').length), 1)
  await page.evaluate(() => { window.workflowAudit.failInbox = false })
  await inbox.getByRole('button', { name: '重试读取', exact: true }).click()
  await inbox.getByRole('button', { name: /调研.md/ }).waitFor()
  await inbox.getByRole('button', { name: '返回全部文件', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.inbox-browser'))
  checks.push('Actual access errors stay local with collapsed details, retry works and write failure does not create a note; the rest of the workspace stays usable')

  await page.evaluate(() => window.workflowAudit.router.push({ name: 'Inbox' }))
  await inbox.getByRole('button', { name: /调研.md/ }).waitFor()
  for (const style of ['soft', 'neo', 'glass', 'airy', 'minimal', 'sharp']) {
    for (const width of [1280, 320]) {
      await page.setViewportSize({ width, height: 850 })
      await page.evaluate(style => { window.workflowAudit.store.visualStyle = style; window.workflowAudit.store.theme = style === 'glass' ? 'blue' : 'white' }, style)
      await page.waitForFunction(style => document.body.dataset.style === style, style)
      const geometry = await inbox.evaluate(el => ({ style: document.body.dataset.style, width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth || el.scrollWidth > el.clientWidth, radius: getComputedStyle(el).borderRadius }))
      assert.equal(geometry.overflow, false, `${style} at ${width} has no horizontal overflow`)
      assert.equal(await inbox.getByRole('button', { name: '新建笔记', exact: true }).isVisible(), true)
      layouts.push(geometry)
    }
  }
  await page.setViewportSize({ width: 1280, height: 850 })
  await page.evaluate(() => { window.workflowAudit.store.visualStyle = 'soft'; window.workflowAudit.store.theme = 'green' })
  await page.screenshot({ path: output + '/04-standalone-green.png' })
  await page.evaluate(() => window.workflowAudit.router.push({ name: 'LibraryMode' }))
  await page.locator('.inbox-shortcut').click()
  await inbox.getByRole('button', { name: /调研.md/ }).waitFor()
  await inbox.screenshot({ path: output + '/02-files-green.png' })
  await inbox.getByRole('button', { name: /调研.md/ }).click()
  await page.waitForFunction(() => window.workflowAudit.store.activeTabId.endsWith('/调研.md'))
  checks.push('Standalone and sidebar keep opening files, six theme styles and narrow layouts; both retain the original functionality')
  assert.deepEqual(errors, [])
  await fs.writeFile(output + '/results.json', JSON.stringify({ checks, layouts, errors, scope: 'Actual App/LibraryMode/InboxView with isolated mocked native IPC; native folder semantics tested separately.' }, null, 2))
  console.log(JSON.stringify({ checks, layouts: layouts.length, errors }, null, 2))
} finally { await browser.close() }
