import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.LONGEDIT_PLAYWRIGHT_MODULE || 'playwright')
const output = path.resolve('docs/evidence/v110-workbook-validation-browser')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const validationErrors = []
  await page.exposeFunction('recordValidationError', text => validationErrors.push(text))
  await page.goto('http://127.0.0.1:9000/scripts/fixtures/workbook-save-browser.html')
  await page.evaluate(() => {
    new MutationObserver(() => {
      for (const element of document.querySelectorAll('.n-message--error-type')) {
        if (element.dataset.auditRecorded) continue
        element.dataset.auditRecorded = 'true'
        window.recordValidationError(element.textContent)
      }
    }).observe(document.body, { childList: true, subtree: true })
  })
  await page.locator('.workbook-cell').first().click()
  await page.locator('.tool-panel-trigger').click()
  await page.getByText('数据、Table 与规则', { exact: true }).click()
  const create = page.getByRole('button', { name: '新建验证', exact: true })
  await create.click()
  const answer = async (title, value, button) => {
    const dialog = page.getByRole('dialog').filter({ hasText: title })
    if (value !== null) await dialog.locator('input, textarea').fill(value)
    await dialog.getByRole('button', { name: button, exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
  }
  await answer('数据验证类型', null, '取消')
  assert.equal(await page.evaluate(() => window.workbookAudit.validationWrites.length), 0)
  await create.click()
  await answer('数据验证类型', 'list', '下一步')
  await answer('数据验证来源或公式', '"待处理,已完成"', '下一步')
  await answer('数据验证错误提示', '请从任务状态列表中选择', '下一步')
  await page.getByRole('dialog').filter({ hasText: '单元格输入提示' }).locator('textarea').fill('选择当前任务状态')
  await page.getByRole('button', { name: '保存规则', exact: true }).waitFor()
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '01-validation-prompt.png') })
  await answer('单元格输入提示', null, '保存规则')
  await page.getByRole('button', { name: '编辑验证', exact: true }).waitFor()
  const writes = await page.evaluate(() => window.workbookAudit.validationWrites)
  assert.equal(writes.length, 1); assert.equal(writes[0].sheet, 'Sheet1')
  assert.equal(writes[0].validation.formula1, '"待处理,已完成"')
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  assert.deepEqual(validationErrors, [], 'creating a rule must not report unchanged existing content as a new invalid edit')
  const formula = page.locator('input[placeholder="当前单元格不可编辑"]')
  await formula.fill('其他状态'); await formula.press('Enter')
  await page.getByText('请从任务状态列表中选择', { exact: true }).waitFor()
  assert.ok(validationErrors.some(text => text.includes('请从任务状态列表中选择')), 'error observer must capture genuine invalid input')
  assert.equal(await page.locator('.workbook-cell').first().locator('.cell-content').innerText(), '确认交付日期')
  await formula.press('Escape')
  await page.waitForFunction(() => document.querySelectorAll('.n-message').length === 0)
  await page.getByRole('button', { name: '删除验证', exact: true }).click()
  await answer('删除数据验证规则？', null, '取消')
  assert.equal(await page.evaluate(() => window.workbookAudit.validationWrites.length), 1)
  await page.getByRole('button', { name: '删除验证', exact: true }).click()
  await page.getByRole('button', { name: '删除规则', exact: true }).waitFor()
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '02-delete-confirmation.png') })
  await page.evaluate(() => { window.workbookAudit.holdValidation = true })
  await page.getByRole('button', { name: '删除规则', exact: true }).click()
  await page.waitForFunction(() => !!window.workbookAudit.pendingValidation)
  await page.evaluate(() => window.workbookAudit.pendingValidation(true))
  await page.getByText('tasks.xlsx 数据验证保存失败：模拟规则写入失败', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.workbookAudit.validationWrites.length), 1)
  await page.getByRole('button', { name: '编辑验证', exact: true }).waitFor()
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, '03-write-failure.png') })
  await page.evaluate(() => { window.workbookAudit.holdValidation = false })
  await page.getByRole('button', { name: '删除验证', exact: true }).click()
  await page.getByRole('button', { name: '删除规则', exact: true }).click()
  await create.waitFor()
  assert.equal(await page.evaluate(() => window.workbookAudit.validationWrites.length), 2)
  assert.deepEqual(errors, [])
  console.log('PASS: actual WorkbookView validation create/cancel/delete and write failure/retry; simulated IPC only')
} finally { await browser.close() }
